// The library, as a table: each line is an expression over a group's inputs.
// `Conformance.test.ts` writes an aggregate that computes every one of them,
// has the prover read it, and has the real code run on the same inputs.
//
// Each expression is read twice: once on inputs the prover knows (a value the
// code writes), and once on inputs the solver holds, pinned to the same
// value. The first is the library computed as it is, the second the formula
// the prover gives it; both have to be what the real code gives.

/** A function written both ways: `f(self, ...args)` and `pipe(self, f(...args))`. */
const d = (fn: string, self: string, ...args: ReadonlyArray<string>): ReadonlyArray<string> => [
  `${fn}(${[self, ...args].join(", ")})`,
  `pipe(${self}, ${fn}(${args.join(", ")}))`,
];

/** A function of an order, written both ways. */
const o = (fn: string, by: string, self: string, arg: string): ReadonlyArray<string> => [
  `${fn}(${by})(${self}, ${arg})`,
  `pipe(${self}, ${fn}(${by})(${arg}))`,
];

/** A sequence of numbers that is the same every run: the grids are fixed, and wide. */
const seeded = (seed: number) => {
  let state = seed;
  return (from: number, to: number): number => {
    state = (state * 1103515245 + 12345) % 2147483648;
    return from + (state % (to - from + 1));
  };
};

/** The pins a group names, and so many more drawn from a fixed sequence, as source. */
const pinned = <A>(
  named: ReadonlyArray<A>,
  more: number,
  draw: (next: ReturnType<typeof seeded>) => A,
  seed: number,
): string => {
  const next = seeded(seed);
  const drawn = Array.from({ length: more }, () => draw(next));
  const seen = new Set<string>();
  return JSON.stringify(
    [...named, ...drawn].filter((pin) => {
      const key = JSON.stringify(pin);
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    }),
  );
};

const LETTERS = ["", "a", "b", "ab", "z", "an", ",", " ", "ba", "A"];
const text = (next: ReturnType<typeof seeded>, parts: number): string =>
  Array.from({ length: next(0, parts) }, () => LETTERS[next(1, LETTERS.length - 1)]).join("");
const list = (next: ReturnType<typeof seeded>, least: number, most: number): Array<number> =>
  Array.from({ length: next(least, most) }, () => next(-6, 6));
const distinct = (items: ReadonlyArray<number>): Array<number> => [...new Set(items)];

export interface Group {
  readonly name: string;
  /** The command's input fields, as schema source. */
  readonly input: string;
  /** The values the inputs are pinned to, one object for each. */
  readonly pins: string;
  /** Whether the command's inputs are other than the pin. */
  readonly differs: string;
  /** The inputs as local variables: `command` holds the solver's, `pin` the known ones. */
  readonly bind: (known: boolean) => string;
  /** Whether each expression is an effect, to be yielded. */
  readonly effectful?: boolean;
  /** Read on inputs the solver holds, and on ones the prover knows. */
  readonly both: ReadonlyArray<string>;
  /** Read only on inputs the prover knows. */
  readonly known?: ReadonlyArray<string>;
  /** How many expressions one command computes: fewer, where each splits the path many ways. */
  readonly chunk?: number;
  /**
   * What the prover does not read, each with what its report has to say. A
   * form in this list is one the prover stops at: it is never read as
   * something else.
   */
  readonly unread?: ReadonlyArray<readonly [expression: string, reason: RegExp]>;
  /** Lines the group's file declares before its commands. */
  readonly prelude?: ReadonlyArray<string>;
  /** The functions the prelude exports that the prover is told not to read. */
  readonly opaque?: ReadonlyArray<string>;
}

