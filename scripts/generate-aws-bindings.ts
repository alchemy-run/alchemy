/**
 * Generate AWS bindings: one `<Op>.ts` per configured distilled operation,
 * holding the `Binding.Service` contract and its `<Op>Http` layer.
 *
 *   node scripts/generate-aws-bindings.ts                  # every configured service
 *   node scripts/generate-aws-bindings.ts SQS              # one service
 *   node scripts/generate-aws-bindings.ts --report SQS     # classify + least-privilege audit, write nothing
 *   node scripts/generate-aws-bindings.ts --changes        # regenerate, then list what changed
 *   node scripts/generate-aws-bindings.ts --check          # fail if any generated file is stale
 *   node scripts/generate-aws-bindings.ts --refresh-actions  # re-snapshot actions.json
 *
 * Inputs, in `packages/aws/bindings/`:
 *
 * - `<Service>.json`: the distilled module, the service's resources, the
 *   per-service builders in `BindingHttp.ts` that implement the layers, and
 *   one entry per binding (operation, bound resource, request shape,
 *   builder, IAM actions, and builder options).
 * - `<Service>.md`: each binding's JSDoc body under `## <Binding>` (and
 *   its request interface's under `## <Binding>.Request`). A binding with
 *   no section gets docs derived from distilled.
 * - `actions.json`: AWS's Service Authorization Reference, cut to what the
 *   audit reads: per service prefix, the IAM actions each API operation
 *   authorizes and the resource types each action can be scoped to.
 *
 * Each distilled operation of a configured service is classified:
 *
 * - `binding`: generated from the config;
 * - `covered`: a hand-written binding in the service calls it;
 * - `unbound`: neither (reported; add it to the config, or leave it to the
 *   resource provider that owns it).
 *
 * The audit compares each generated binding's actions with the actions AWS
 * says its operation authorizes: `missing` (granted fewer; the call can be
 * denied), `extra` (granted more), and, for a builder that grants on `*`,
 * `scopable` (the actions accept a resource ARN, so `*` is broader than
 * needed). Builders declare where they grant (`grants`) in the config.
 */
import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const bindingsDir = path.join(root, "packages/aws/bindings");
const srcDir = path.join(root, "packages/aws/src");
const distilledDir = path.join(root, "submodules/distilled/packages/aws/src/services");
const HEADER = (service: string) =>
  `// @generated by scripts/generate-aws-bindings.ts from packages/aws/bindings/${service}.json. Do not edit.\n`;
const HEADER_PREFIX = "// @generated by scripts/generate-aws-bindings.ts";

// ============ Config ============

type OptionKind = "tag" | "name" | "operation" | "actions";
type Literal = string | number | boolean | string[];

interface BuilderConfig {
  /** The module exporting the builder, relative to the service directory. */
  file?: string;
  /**
   * The builder's option keys and what fills each, when they aren't
   * `{ tag, operation, actions }`: `{ "capability": "name", "iamActions": "actions", "operation": "operation" }`.
   */
  options?: Record<string, OptionKind>;
  /**
   * Where the builder grants the actions: `"resource"` (the bound
   * resource's ARN, or ARNs derived from it) or `"*"`. Read by the audit.
   */
  grants?: "resource" | "*";
}

interface RequestConfig {
  /** `optional` (default): `request?`; `required`: `request`; `none`: a callable that takes no request. */
  mode?: "optional" | "required" | "none";
  /** Export the request as this interface (`SendMessageRequest`) instead of using the distilled type directly. */
  interface?: string;
  /** Members the builder injects from the bound resource, omitted from the caller's request. */
  omit?: string[];
  /** Write the `Omit<…>` inline in the signature instead of as an interface. */
  inline?: boolean;
  /** The distilled request type, when it isn't the operation's input type. */
  base?: string;
}

interface BindingConfig {
  /** The distilled operation, e.g. `sendMessage`. */
  operation: string;
  /** The distilled module when it isn't the service's. */
  module?: string;
  alias?: string;
  /** The resource the binding is bound to (a key of `resources`), or a union of them. */
  resource?: string | string[];
  /** The bound resource's parameter name, when it isn't the resource name in camelCase. */
  param?: string;
  request?: RequestConfig;
  /** The builder implementing the layer, when it isn't the service's `builder`. */
  builder?: string;
  /** The option template for this binding, when it differs from its builder's. */
  options?: Record<string, OptionKind>;
  /** IAM actions granted. */
  actions?: string[];
  /** More builder options, as literals. */
  with?: Record<string, Literal>;
  /** More builder options, as TypeScript expressions. */
  withTs?: Record<string, string>;
  /**
   * Imports the `withTs` expressions use: module → names, or `"* as X"`
   * for a namespace (`{ "alchemy/Output": "* as Output" }`).
   */
  imports?: Record<string, string[] | string>;
  /** Why the grant looks the way it does; emitted as a comment on the layer. */
  note?: string;
  /** The distilled response or error type, when it isn't the operation's. */
  response?: string;
  error?: string;
}

interface ServiceConfig {
  /** Binding tag prefix, e.g. `AWS.SQS`. */
  tag: string;
  /** Distilled module, e.g. `sqs` (`@distilled.cloud/aws/sqs`). */
  module: string;
  /** Import alias, when it isn't the module name without punctuation. */
  alias?: string;
  /** Resource name → the module declaring it. */
  resources: Record<string, { file: string }>;
  /** The builder most bindings use. */
  builder: string;
  builders: Record<string, BuilderConfig>;
  bindings: Record<string, BindingConfig>;
  /** Distilled operation → why it is not a binding. */
  skip?: Record<string, string>;
}

const DEFAULT_OPTIONS: Record<string, OptionKind> = {
  tag: "tag",
  operation: "operation",
  actions: "actions",
};

const aliasOf = (module: string) => module.replace(/[^a-z0-9]/gi, "");

// ============ Distilled ============

interface Operation {
  input: string;
  output: string;
  error: string;
  doc: string | undefined;
}

const moduleCache = new Map<string, Map<string, Operation>>();
const operationsOf = (module: string) => {
  let ops = moduleCache.get(module);
  if (ops) return ops;
  ops = new Map();
  const file = path.join(distilledDir, `${module}.ts`);
  const source = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  for (const m of source.matchAll(
    /(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?export const (\w+): API\.(?:Paginated)?OperationMethod<\s*(\w+)(?: & RegionInput)?,\s*(\w+),\s*(\w+)/g,
  )) {
    ops.set(m[2]!, { input: m[3]!, output: m[4]!, error: m[5]!, doc: m[1] });
  }
  moduleCache.set(module, ops);
  return ops;
};

const firstParagraph = (doc: string | undefined) =>
  doc
    ?.split("\n")
    .map((l) => l.replace(/^\s*\* ?/, ""))
    .join("\n")
    .trim()
    .split(/\n\s*\n/)[0]
    ?.replace(/\s+/g, " ")
    .trim();

// ============ Docs ============

const readDocs = (service: string) => {
  const file = path.join(bindingsDir, `${service}.md`);
  const docs = new Map<string, string>();
  if (!fs.existsSync(file)) return docs;
  const source = fs.readFileSync(file, "utf8");
  const sections = source.split(/^## (\w+(?:\.Request)?)\n/m);
  for (let i = 1; i < sections.length; i += 2) {
    docs.set(sections[i]!, sections[i + 1]!.replace(/^\n/, "").trimEnd());
  }
  return docs;
};

const jsdoc = (body: string, indent = "") => {
  const lines = body.split("\n");
  if (lines.length === 1 && !lines[0]!.includes("*/") && lines[0]!.length < 90) {
    return `${indent}/** ${lines[0]} */`;
  }
  return [
    `${indent}/**`,
    ...lines.map((l) => (l === "" ? `${indent} *` : `${indent} * ${l}`)),
    `${indent} */`,
  ].join("\n");
};

// ============ Emit ============

const camel = (s: string) => s[0]!.toLowerCase() + s.slice(1);

const literal = (v: Literal): string =>
  Array.isArray(v) ? `[${v.map((x) => JSON.stringify(x)).join(", ")}]` : JSON.stringify(v);

const emitBinding = (
  service: string,
  config: ServiceConfig,
  name: string,
  binding: BindingConfig,
  docs: Map<string, string>,
) => {
  const module = binding.module ?? config.module;
  const alias =
    binding.alias ?? (binding.module ? aliasOf(module) : (config.alias ?? aliasOf(module)));
  const op = operationsOf(module).get(binding.operation);
  if (op === undefined) {
    throw new Error(`${service}.${name}: no distilled operation ${module}.${binding.operation}`);
  }
  const tag = `${config.tag}.${name}`;
  const builderName = binding.builder ?? config.builder;
  const builder = config.builders[builderName];
  if (builder === undefined) throw new Error(`${service}.${name}: unknown builder ${builderName}`);
  const resources =
    binding.resource === undefined
      ? []
      : Array.isArray(binding.resource)
        ? binding.resource
        : [binding.resource];
  for (const r of resources) {
    if (config.resources[r] === undefined) {
      throw new Error(`${service}.${name}: unknown resource ${r}`);
    }
  }
  const request = binding.request ?? {};
  const mode = request.mode ?? "optional";
  const base = `${alias}.${request.base ?? op.input}`;
  const omitted = (request.omit ?? []).map((m) => JSON.stringify(m)).join(" | ");
  const baseType = request.omit?.length ? `Omit<${base}, ${omitted}>` : base;

  const imports = new Map<string, string>();
  imports.set(
    `@distilled.cloud/aws/${module}`,
    `import * as ${alias} from "@distilled.cloud/aws/${module}";`,
  );
  imports.set("alchemy/Binding", `import * as Binding from "alchemy/Binding";`);
  imports.set("effect/Effect", `import type * as Effect from "effect/Effect";`);
  imports.set("effect/Layer", `import * as Layer from "effect/Layer";`);
  // spec → name → whether it is only used as a type
  const named = new Map<string, Map<string, boolean>>();
  const addNamed = (spec: string, n: string, type: boolean) => {
    const entry = named.get(spec) ?? new Map<string, boolean>();
    entry.set(n, (entry.get(n) ?? true) && type);
    named.set(spec, entry);
  };
  addNamed(`./${builder.file ?? "BindingHttp.ts"}`, builderName, false);
  for (const r of resources) addNamed(`./${config.resources[r]!.file}`, r, true);
  for (const [spec, names] of Object.entries(binding.imports ?? {})) {
    if (typeof names === "string") imports.set(spec, `import ${names} from "${spec}";`);
    else for (const n of names) addNamed(spec, n, false);
  }
  for (const [spec, names] of named) {
    const entries = [...names].sort(([a], [b]) => a.localeCompare(b));
    const allTypes = entries.every(([, type]) => type);
    const list = entries.map(([n, type]) => (type && !allTypes ? `type ${n}` : n)).join(", ");
    imports.set(spec, `import ${allTypes ? "type " : ""}{ ${list} } from "${spec}";`);
  }

  const parts: string[] = [HEADER(service) + [...imports.values()].join("\n"), ""];
  let requestType = base;
  if (mode !== "none") {
    if (request.interface) {
      const reqDoc = docs.get(`${name}.Request`);
      if (reqDoc) parts.push(jsdoc(reqDoc));
      parts.push(`export interface ${request.interface} extends ${baseType} {}`, "");
      requestType = request.interface;
    } else {
      requestType = baseType;
    }
  }
  const doc =
    docs.get(name) ??
    [
      `Runtime binding for \`${(binding.actions ?? [])[0] ?? `${module}:${binding.operation}`}\`.`,
      "",
      ...(firstParagraph(op.doc) ? [firstParagraph(op.doc)!, ""] : []),
      `Provide the implementation with \`Effect.provide(AWS.${service}.${name}Http)\`.`,
      "",
      "@binding",
    ].join("\n");
  parts.push(jsdoc(doc));
  const paramList =
    resources.length === 0
      ? ""
      : `${binding.param ?? camel(resources[0]!)}: ${resources.join(" | ")}`;
  const requestParam =
    mode === "none" ? "" : `request${mode === "optional" ? "?" : ""}: ${requestType}`;
  const response = `${alias}.${binding.response ?? op.output}`;
  const error = `${alias}.${binding.error ?? op.error}`;
  parts.push(
    `export interface ${name} extends Binding.Service<`,
    `  ${name},`,
    `  ${JSON.stringify(tag)},`,
    `  (${paramList}) => Effect.Effect<(${requestParam}) => Effect.Effect<${response}, ${error}>>`,
    `> {}`,
    "",
    `export const ${name} = Binding.Service<${name}>(${JSON.stringify(tag)});`,
    "",
  );
  const template = binding.options ?? builder.options ?? DEFAULT_OPTIONS;
  const options: string[] = [];
  for (const [key, kind] of Object.entries(template)) {
    const value =
      kind === "tag"
        ? JSON.stringify(tag)
        : kind === "name"
          ? JSON.stringify(name)
          : kind === "operation"
            ? `${alias}.${binding.operation}`
            : literal(binding.actions ?? []);
    options.push(`    ${key}: ${value},`);
  }
  for (const [key, value] of Object.entries(binding.with ?? {})) {
    options.push(`    ${key}: ${literal(value)},`);
  }
  for (const [key, value] of Object.entries(binding.withTs ?? {})) {
    options.push(`    ${key}: ${value},`);
  }
  parts.push(
    `export const ${name}Http = Layer.effect(`,
    `  ${name},`,
    ...(binding.note ? [`  // ${binding.note}`] : []),
    `  ${builderName}({`,
    ...options,
    `  }),`,
    `);`,
    "",
  );
  return parts.join("\n");
};

// ============ Classification ============

interface Classified {
  operation: string;
  kind: "binding" | "covered" | "skip" | "unbound";
  name?: string;
  reason?: string;
}

/** Distilled operations hand-written bindings in the service call, per module. */
const handWrittenCalls = (serviceDir: string, generated: Set<string>) => {
  const calls = new Map<string, Set<string>>();
  for (const file of fs.readdirSync(serviceDir).filter((f) => f.endsWith(".ts"))) {
    if (generated.has(file)) continue;
    const source = fs.readFileSync(path.join(serviceDir, file), "utf8");
    if (!/export const \w+Http\b/.test(source) && !file.endsWith("Http.ts")) continue;
    for (const imp of source.matchAll(
      /import (?:type )?\* as (\w+) from "@distilled\.cloud\/aws\/([\w-]+)"/g,
    )) {
      const ops = calls.get(imp[2]!) ?? new Set<string>();
      for (const m of source.matchAll(new RegExp(`\\b${imp[1]}\\.(\\w+)\\b`, "g"))) ops.add(m[1]!);
      calls.set(imp[2]!, ops);
    }
  }
  return calls;
};

// ============ Least privilege ============

interface ActionsTable {
  [prefix: string]: {
    /** Action → resource types it can be scoped to (empty: only `*`). */
    actions: Record<string, string[]>;
    /** API operation → the actions it authorizes (`service:Action`). */
    operations: Record<string, string[]>;
  };
}

interface Finding {
  name: string;
  kind: "missing" | "extra" | "scopable" | "unknown";
  detail: string;
}

const audit = (config: ServiceConfig, actionsTable: ActionsTable): Finding[] => {
  const findings: Finding[] = [];
  for (const [name, binding] of Object.entries(config.bindings)) {
    const granted = binding.actions ?? [];
    const prefixes = new Set(granted.map((a) => a.split(":")[0]!));
    const apiOperation = binding.operation[0]!.toUpperCase() + binding.operation.slice(1);
    let needed: string[] | undefined;
    for (const prefix of prefixes) {
      const ops = actionsTable[prefix]?.operations;
      const hit =
        ops && Object.keys(ops).find((k) => k.toLowerCase() === apiOperation.toLowerCase());
      if (hit) needed = ops[hit];
    }
    if (needed === undefined || needed.length === 0) {
      findings.push({
        name,
        kind: "unknown",
        detail: `AWS publishes no actions for ${apiOperation}`,
      });
      continue;
    }
    const lower = (xs: string[]) => new Set(xs.map((x) => x.toLowerCase()));
    const g = lower(granted);
    const n = lower(needed);
    const missing = needed.filter((a) => !g.has(a.toLowerCase()));
    const extra = granted.filter((a) => !n.has(a.toLowerCase()));
    if (missing.length) findings.push({ name, kind: "missing", detail: missing.join(", ") });
    if (extra.length) findings.push({ name, kind: "extra", detail: extra.join(", ") });
    const builder = config.builders[binding.builder ?? config.builder];
    if (builder?.grants === "*") {
      const scopable = granted.filter((a) => {
        const [prefix, action] = a.split(":") as [string, string];
        const entry = actionsTable[prefix]?.actions;
        const key =
          entry && Object.keys(entry).find((k) => k.toLowerCase() === action.toLowerCase());
        return key !== undefined && entry![key]!.length > 0;
      });
      if (scopable.length) {
        findings.push({ name, kind: "scopable", detail: `${scopable.join(", ")} on * ` });
      }
    }
  }
  return findings;
};

const refreshActions = () => {
  const curl = (url: string) =>
    execFileSync("curl", ["-sf", url], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  const index = JSON.parse(curl("https://servicereference.us-east-1.amazonaws.com/")) as {
    service: string;
    url: string;
  }[];
  // Only the prefixes AWS bindings grant: the table stays small.
  const used = new Set<string>();
  for (const file of fs
    .readdirSync(bindingsDir)
    .filter((f) => f.endsWith(".json") && f !== "actions.json")) {
    const config = JSON.parse(
      fs.readFileSync(path.join(bindingsDir, file), "utf8"),
    ) as ServiceConfig;
    for (const b of Object.values(config.bindings))
      for (const a of b.actions ?? []) used.add(a.split(":")[0]!);
  }
  const table: ActionsTable = {};
  for (const entry of index.filter((e) => used.has(e.service))) {
    const doc = JSON.parse(curl(entry.url)) as {
      Actions?: { Name: string; Resources?: { Name: string }[] }[];
      Operations?: { Name: string; AuthorizedActions?: { Name: string; Service: string }[] }[];
    };
    table[entry.service] = {
      actions: Object.fromEntries(
        (doc.Actions ?? []).map((a) => [a.Name, (a.Resources ?? []).map((r) => r.Name)]),
      ),
      operations: Object.fromEntries(
        (doc.Operations ?? []).map((o) => [
          o.Name,
          (o.AuthorizedActions ?? []).map((x) => `${x.Service}:${x.Name}`),
        ]),
      ),
    };
  }
  const sorted = Object.fromEntries(Object.entries(table).sort(([a], [b]) => a.localeCompare(b)));
  const out = path.join(bindingsDir, "actions.json");
  fs.writeFileSync(out, `${JSON.stringify(sorted)}\n`);
  execFileSync("pnpm", ["exec", "oxfmt", out], { cwd: root, stdio: "ignore" });
  console.log(`actions.json: ${Object.keys(sorted).length} services`);
};

// ============ Generate ============

const readConfig = (service: string) =>
  JSON.parse(fs.readFileSync(path.join(bindingsDir, `${service}.json`), "utf8")) as ServiceConfig;

const generateService = (
  service: string,
  report: boolean,
  actionsTable: ActionsTable | undefined,
) => {
  const config = readConfig(service);
  const docs = readDocs(service);
  const serviceDir = path.join(srcDir, service);
  const files = fs.readdirSync(serviceDir).filter((f) => f.endsWith(".ts"));
  const generated = new Set(
    files.filter((f) =>
      fs.readFileSync(path.join(serviceDir, f), "utf8").startsWith(HEADER_PREFIX),
    ),
  );
  // classify every operation of the service's modules
  const modules = new Set([
    config.module,
    ...Object.values(config.bindings).flatMap((b) => (b.module ? [b.module] : [])),
  ]);
  const configured = new Map(
    Object.entries(config.bindings).map(([n, b]) => [
      `${b.module ?? config.module}.${b.operation}`,
      n,
    ]),
  );
  const calls = handWrittenCalls(
    serviceDir,
    new Set([...generated, ...Object.keys(config.bindings).map((n) => `${n}.ts`)]),
  );
  const results: Classified[] = [];
  for (const module of modules) {
    for (const operation of operationsOf(module).keys()) {
      const name = configured.get(`${module}.${operation}`);
      if (name) results.push({ operation, kind: "binding", name });
      else if (calls.get(module)?.has(operation)) results.push({ operation, kind: "covered" });
      else if (config.skip?.[operation])
        results.push({ operation, kind: "skip", reason: config.skip[operation] });
      else results.push({ operation, kind: "unbound" });
    }
  }
  const counts: Record<string, number> = {};
  for (const r of results) counts[r.kind] = (counts[r.kind] ?? 0) + 1;
  console.log(
    `${service}: ${Object.entries(counts)
      .map(([k, v]) => `${k}=${v}`)
      .join(" ")}`,
  );
  const findings = actionsTable ? audit(config, actionsTable) : [];
  if (report) {
    for (const f of findings) console.log(`  ${f.kind.padEnd(9)} ${f.name}  ${f.detail}`);
    for (const r of results.filter((r) => r.kind === "unbound"))
      console.log(`  unbound   ${r.operation}`);
    return findings;
  }

  const written = new Set<string>();
  for (const [name, binding] of Object.entries(config.bindings)) {
    const file = `${name}.ts`;
    const target = path.join(serviceDir, file);
    if (fs.existsSync(target) && !generated.has(file)) {
      // The first generation replaces the hand-written file it was derived from.
      const source = fs.readFileSync(target, "utf8");
      if (!new RegExp(`export const ${name}Http\\b`).test(source)) {
        throw new Error(`${service}/${file} is hand-written and isn't a binding; rename ${name}`);
      }
    }
    fs.writeFileSync(target, emitBinding(service, config, name, binding, docs));
    written.add(file);
  }
  for (const file of generated) {
    if (!written.has(file) && file !== "generated.ts") fs.unlinkSync(path.join(serviceDir, file));
  }
  // generated.ts lists the generated bindings; index.ts re-exports it once.
  fs.writeFileSync(
    path.join(serviceDir, "generated.ts"),
    `${HEADER(service)}${
      [...written]
        .sort()
        .map((f) => `export * from "./${f}";`)
        .join("\n") || "export {};"
    }\n`,
  );
  const indexPath = path.join(serviceDir, "index.ts");
  const index = fs
    .readFileSync(indexPath, "utf8")
    .split("\n")
    .filter((line) => {
      const m = /^export \* from "\.\/(\w+\.ts)";$/.exec(line);
      return !(m && written.has(m[1]!));
    })
    .join("\n")
    .trimEnd();
  fs.writeFileSync(
    indexPath,
    index.includes(`"./generated.ts"`)
      ? `${index}\n`
      : `${index}\nexport * from "./generated.ts";\n`,
  );
  execFileSync(
    "pnpm",
    [
      "exec",
      "oxfmt",
      ...[...written, "generated.ts", "index.ts"].map((f) => path.join(serviceDir, f)),
    ],
    { cwd: root, stdio: "ignore" },
  );
  return findings;
};

// ============ Changes ============

const git = (args: string[]) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 256 * 1024 * 1024 });

const sections = (source: string) => {
  const take = (re: RegExp) => {
    const m = re.exec(source);
    if (!m) return "";
    source = source.replace(m[0], "");
    return m[0];
  };
  const request = take(/export interface \w+Request\b[\s\S]*?\{\}\n/);
  const signature = take(/export interface \w+ extends Binding\.Service<[\s\S]*?\n> \{\}\n/);
  const layer = take(/export const \w+Http = Layer\.effect\([\s\S]*?\n\);\n/);
  const actions = /actions: (\[[^\]]*\])|iamActions: (\[[^\]]*\])/.exec(layer)?.[0] ?? "";
  return {
    request,
    signature,
    actions,
    layer: layer.replace(actions, ""),
    docs: source,
  };
};

const reportChanges = () => {
  const status = git(["status", "--porcelain", "--untracked-files=all", "--", "packages/aws/src"]);
  const byService = new Map<string, string[]>();
  for (const line of status.split("\n").filter(Boolean)) {
    const code = line.slice(0, 2);
    const file = line.slice(3);
    const m = /^packages\/aws\/src\/(\w+)\/(\w+)\.ts$/.exec(file);
    if (!m || m[2] === "generated" || m[2] === "index") continue;
    const [, service, name] = m as unknown as [string, string, string];
    const lines = byService.get(service) ?? [];
    if (code.includes("?") || code.includes("A")) lines.push(`  added      ${name}`);
    else if (code.includes("D")) lines.push(`  removed    ${name}`);
    else {
      const before = sections(git(["show", `HEAD:${file}`]));
      const after = sections(fs.readFileSync(path.join(root, file), "utf8"));
      const aspects = (Object.keys(before) as (keyof typeof before)[]).filter(
        (k) => before[k] !== after[k],
      );
      lines.push(`  changed    ${name}  [${aspects.join(", ") || "format"}]`);
    }
    byService.set(service, lines);
  }
  if (byService.size === 0) {
    console.log("No binding changes.");
    return;
  }
  for (const [service, lines] of [...byService].sort(([a], [b]) => a.localeCompare(b))) {
    console.log(`\n${service}\n${lines.sort().join("\n")}`);
  }
};

// ============ CLI ============

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith("--")));
const named = args.filter((a) => !a.startsWith("--"));
if (flags.has("--refresh-actions")) {
  refreshActions();
  if (named.length === 0) process.exit(0);
}
const all = fs
  .readdirSync(bindingsDir)
  .filter((f) => f.endsWith(".json") && f !== "actions.json")
  .map((f) => f.slice(0, -5))
  .sort();
const actionsPath = path.join(bindingsDir, "actions.json");
const actionsTable = fs.existsSync(actionsPath)
  ? (JSON.parse(fs.readFileSync(actionsPath, "utf8")) as ActionsTable)
  : undefined;
const report = flags.has("--report");
const totals: Record<string, number> = {};
for (const service of named.length ? named : all) {
  for (const f of generateService(service, report, actionsTable))
    totals[f.kind] = (totals[f.kind] ?? 0) + 1;
}
if (report && actionsTable) {
  console.log(
    `\nleast privilege: ${
      Object.entries(totals)
        .map(([k, v]) => `${k}=${v}`)
        .join(" ") || "clean"
    }`,
  );
}
if (flags.has("--changes") && !report) reportChanges();
if (flags.has("--check")) {
  const status = git(["status", "--porcelain", "--", "packages/aws/src", "packages/aws/bindings"]);
  if (status.trim()) {
    console.error(
      `Generated AWS bindings are out of date; run \`node scripts/generate-aws-bindings.ts\` and commit:\n${status}`,
    );
    process.exit(1);
  }
  console.log("Generated AWS bindings are up to date.");
}
