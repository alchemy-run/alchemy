import * as apim from "@distilled.cloud/azure/apimanagement";
import * as Provider from "alchemy/Provider";
import type { Resource } from "alchemy/Resource";
import * as Effect from "effect/Effect";
import * as Redacted from "effect/Redacted";
import type { Providers } from "../Providers.ts";
import { GroupedResource } from "../StackResourceGroup.ts";
import { entityLifecycle, reveal } from "./Entity.ts";

export type TenantAccessName = apim.CreateTenantAccessRequestAccessName;

export interface TenantAccessProps {
  /**
   * Resource group of the API Management service.
   * Changing it replaces the access configuration.
   */
  resourceGroup: string;
  /**
   * API Management service the configuration belongs to.
   * Changing it replaces the access configuration.
   */
  serviceName: string;
  /**
   * Which access configuration to manage: `access` (the direct management
   * REST API) or `gitAccess` (the configuration Git repository).
   * Changing it replaces the access configuration.
   * @default "access"
   */
  accessName?: TenantAccessName;
  /** Whether the access is enabled. */
  enabled: boolean;
  /**
   * Principal (user) the access keys sign in as.
   * @default the service's built-in `integration` principal
   */
  principalId?: string;
  /** Primary access key. Generated by API Management if omitted. */
  primaryKey?: Redacted.Redacted<string>;
  /** Secondary access key. Generated by API Management if omitted. */
  secondaryKey?: Redacted.Redacted<string>;
}

export interface TenantAccess extends Resource<
  "Azure.ApiManagement.TenantAccess",
  TenantAccessProps,
  {
    /** Access configuration name (`access` or `gitAccess`). */
    accessName: string;
    /** ARM resource ID of the access configuration. */
    tenantAccessId: string;
    /** API Management service the configuration belongs to. */
    serviceName: string;
    /** Resource group of the service. */
    resourceGroup: string;
    /** Whether the access is enabled. */
    enabled: boolean;
    /** Principal (user) the access keys sign in as. */
    principalId: string | undefined;
    /** Primary access key. */
    primaryKey: Redacted.Redacted<string> | undefined;
    /** Secondary access key. */
    secondaryKey: Redacted.Redacted<string> | undefined;
  },
  never,
  Providers
> {}

/**
 * The tenant access settings of an API Management service
 * (`Microsoft.ApiManagement/service/tenant`): whether the direct
 * management REST API (`access`) or the configuration Git repository
 * (`gitAccess`) is enabled, and their keys. Both configurations always
 * exist; deleting the resource disables the access. Only the classic
 * Developer, Basic, Standard, and Premium tiers support it.
 *
 * :::caution
 * Changing `accessName`, `serviceName`, or `resourceGroup` replaces the
 * access configuration.
 * :::
 *
 * @see https://learn.microsoft.com/rest/api/apimanagement/tenant-access
 *
 * ### Enabling Direct Management Access
 * **Example:** Enable the direct management API and read its key
 * ```typescript
 * const access = yield* Azure.ApiManagement.TenantAccess("management", {
 *   serviceName: apim.serviceName,
 *   enabled: true,
 * });
 * // access.primaryKey signs SharedAccessSignature tokens for the API.
 * ```
 *
 * @resource
 */
export const TenantAccess = GroupedResource<TenantAccess>("Azure.ApiManagement.TenantAccess");

interface Key {
  resourceGroup: string;
  serviceName: string;
  accessName: string;
}

const where = (subscriptionId: string, key: Key) => ({
  subscriptionId,
  resourceGroupName: key.resourceGroup,
  serviceName: key.serviceName,
  accessName: key.accessName,
});

export const TenantAccessProvider = () =>
  Provider.succeed(TenantAccess, {
    stables: ["accessName", "tenantAccessId", "serviceName", "resourceGroup"],
    // Both configurations always exist; nuke has nothing to delete.
    nuke: { singleton: true },
    ...entityLifecycle<
      TenantAccessProps,
      TenantAccess["Attributes"],
      Key,
      apim.GetTenantAccessResponse
    >({
      label: (key) => `API Management tenant access ${key.accessName}`,
      keyOf: (props) =>
        Effect.succeed({
          resourceGroup: props.resourceGroup,
          serviceName: props.serviceName,
          accessName: props.accessName ?? "access",
        }),
      keyOfAttrs: (attrs) => attrs,
      get: (subscriptionId, key) => apim.GetTenantAccess(where(subscriptionId, key)),
      put: (subscriptionId, key, news) =>
        apim.CreateTenantAccess({
          ...where(subscriptionId, key),
          properties: {
            enabled: news.enabled,
            principalId: news.principalId,
            primaryKey: reveal(news.primaryKey),
            secondaryKey: reveal(news.secondaryKey),
          },
        }),
      // The configuration cannot be deleted; disable it instead.
      remove: (subscriptionId, key) =>
        apim.CreateTenantAccess({
          ...where(subscriptionId, key),
          properties: { enabled: false },
        }),
      resetOnDelete: true,
      // GET never returns the keys; compare them against the last props.
      inSync: (news, observed, olds) =>
        observed.properties?.enabled === news.enabled &&
        (news.principalId === undefined || observed.properties.principalId === news.principalId) &&
        reveal(news.primaryKey) === reveal(olds?.primaryKey) &&
        reveal(news.secondaryKey) === reveal(olds?.secondaryKey),
      toAttrs: (_subscriptionId, key, observed) => ({
        resourceGroup: key.resourceGroup,
        serviceName: key.serviceName,
        accessName: key.accessName,
        tenantAccessId: observed.id ?? "",
        enabled: observed.properties?.enabled ?? false,
        principalId: observed.properties?.principalId,
        primaryKey: undefined,
        secondaryKey: undefined,
      }),
      finalize: (subscriptionId, key, attrs) =>
        apim.ListTenantAccessSecrets(where(subscriptionId, key)).pipe(
          Effect.map((secrets) => ({
            ...attrs,
            primaryKey: secrets.primaryKey ? Redacted.make(secrets.primaryKey) : undefined,
            secondaryKey: secrets.secondaryKey ? Redacted.make(secrets.secondaryKey) : undefined,
          })),
        ),
    }),
  });
