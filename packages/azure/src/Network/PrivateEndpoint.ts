export interface PrivateLinkServiceConnectionSpec {
  /**
   * Name of the connection.
   * @default the private endpoint name
   */
  name?: string;
  /**
   * ARM ID of the target resource (e.g. a storage account or Key Vault) or
   * private link service.
   */
  privateLinkServiceId: string;
  /**
   * Target sub-resources, e.g. `["blob"]`, `["file"]`, `["queue"]`, or
   * `["dfs"]` for a storage account, `["vault"]` for Key Vault, or
   * `["registry"]` for a container registry. Omit for a private link
   * service.
   */
  groupIds?: string[];
  /**
   * Message sent to the owner of the target with a manual request (up to
   * 140 characters).
   */
  requestMessage?: string;
}

export interface PrivateEndpointStaticIpConfiguration {
  /** Name of the IP configuration. */
  name: string;
  /** Target sub-resource, e.g. `blob`. */
  groupId: string;
  /** Member name of the sub-resource, e.g. `blob`. */
  memberName: string;
  /** Static private IP inside the subnet, e.g. `10.0.3.10`. */
  privateIpAddress: string;
}

export interface PrivateEndpointProps {
  /**
   * Resource group the private endpoint is created in. Changing it
   * replaces the private endpoint.
   * @default the stack's resource group (`Azure.resourceGroup(...)`, else `<stack>-<stage>`)
   */
  resourceGroup: string;
  /**
   * Name of the private endpoint: 2-64 letters, digits, `_`, `.`, and `-`.
   * If omitted, a unique name is generated from the app, stage, and
   * logical ID. Changing it replaces the private endpoint.
   */
  name?: string;
  /**
   * Azure location; must match the subnet's virtual network. Changing it
   * replaces the private endpoint.
   * @default the `Azure.Location` layer, else the profile location, else `eastus`
   */
  location?: string;
  /**
   * ARM ID of the subnet the endpoint's NIC is placed in. The subnet must
   * not be delegated. Changing it replaces the private endpoint.
   */
  subnetId: string;
  /**
   * Auto-approved connections (targets you own or have access to). Set
   * this or `manualPrivateLinkServiceConnections`. Changing a target or
   * its group IDs replaces the private endpoint.
   */
  privateLinkServiceConnections?: PrivateLinkServiceConnectionSpec[];
  /**
   * Connections that the target's owner must approve (e.g. cross-tenant).
   * Changing them replaces the private endpoint.
   */
  manualPrivateLinkServiceConnections?: PrivateLinkServiceConnectionSpec[];
  /**
   * Name of the endpoint's network interface. Changing it replaces the
   * private endpoint.
   * @default generated by Azure
   */
  customNetworkInterfaceName?: string;
  /**
   * Static IPs for the endpoint. Changing them replaces the private
   * endpoint.
   * @default dynamically allocated
   */
  ipConfigurations?: PrivateEndpointStaticIpConfiguration[];
  /**
   * ARM IDs of application security groups the endpoint joins. Updated in
   * place.
   * @default []
   */
  applicationSecurityGroupIds?: string[];
  /**
   * User tags. Alchemy ownership tags (`alchemy::stack`, `alchemy::stage`,
   * `alchemy::id`) are merged in automatically.
   * @default {}
   */
  tags?: Record<string, string>;
}

export interface PrivateEndpointDnsConfig {
  /** FQDN of the target that resolves to the endpoint. */
  fqdn: string | undefined;
  /** Private IPs of the endpoint for that FQDN. */
  ipAddresses: string[];
}

export interface PrivateEndpoint extends Resource<
  "Azure.Network.PrivateEndpoint",
  PrivateEndpointProps,
  {
    /** Name of the private endpoint. */
    privateEndpointName: string;
    /** ARM resource ID of the private endpoint. */
    privateEndpointId: string;
    /** Resource group that holds the private endpoint. */
    resourceGroup: string;
    /** Azure location of the private endpoint, e.g. `eastus`. */
    location: string;
    /** Subnet the endpoint lives in. */
    subnetId: string;
    /** IDs of the network interfaces Azure created for the endpoint. */
    networkInterfaceIds: string[];
    /** FQDN-to-private-IP mappings (for custom DNS). */
    customDnsConfigs: PrivateEndpointDnsConfig[];
    /**
     * Status of the first connection: `Approved`, `Pending`, `Rejected`,
     * or `Disconnected`.
     */
    connectionStatus: string | undefined;
    /** User tags (Alchemy ownership tags stripped). */
    tags: Record<string, string>;
  },
  never,
  Providers
> {}

/**
 * An Azure private endpoint (`Microsoft.Network/privateEndpoints`): a
 * network interface with a private IP in your subnet that connects to a
 * PaaS resource (Storage, Key Vault, SQL, Container Registry, ...) or a
 * private link service over Azure Private Link. Azure's counterpart to an
 * AWS interface VPC endpoint.
 *
 * Azure creates and owns the endpoint's network interface. Pair the
 * endpoint with a `privatelink.*` Private DNS zone and an
 * `Azure.Network.PrivateDnsZoneGroup` so the target's normal FQDN (e.g.
 * `<account>.blob.core.windows.net`) resolves to the private IP. Until
 * then, `customDnsConfigs` lists the FQDN-to-IP mappings. Set
 * `publicNetworkAccess: "Disabled"` on the target to make the endpoint the
 * only way in.
 *
 * :::caution[Changing `name`, `location`, `resourceGroup`, `subnetId`, a connection's target or group IDs, `customNetworkInterfaceName`, or `ipConfigurations` replaces the private endpoint]
 * Alchemy creates a new endpoint and deletes the old one. The new
 * endpoint gets a new private IP unless you pin one with
 * `ipConfigurations`, and its DNS zone group is recreated with it.
 * Clients that cached the old IP fail until DNS catches up.
 * :::
 *
 * :::caution[The endpoint must be in the same region as its virtual network]
 * The target resource can be in any region. Place the endpoint in a
 * subnet that is not delegated to a service.
 * :::
 *
 * @see https://learn.microsoft.com/azure/private-link/private-endpoint-overview
 *
 * ### Connecting to a Storage Account
 * Use one endpoint per storage service (`blob`, `file`, `queue`, `table`,
 * `dfs`, `web`).
 *
 * **Example:** Private endpoint for blob storage
 * ```typescript
 * const account = yield* Azure.Storage.StorageAccount("files", {
 *   publicNetworkAccess: "Disabled",
 * });
 * const endpoint = yield* Azure.Network.PrivateEndpoint("files-blob", {
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: account.storageAccountId, groupIds: ["blob"] },
 *   ],
 * });
 * ```
 *
 * **Example:** Endpoint with a fixed name and NIC name
 * ```typescript
 * const endpoint = yield* Azure.Network.PrivateEndpoint("files-blob", {
 *   name: "pe-files-blob",
 *   customNetworkInterfaceName: "pe-files-blob-nic",
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: account.storageAccountId, groupIds: ["blob"] },
 *   ],
 * });
 * ```
 *
 * ### Private DNS
 * Create the `privatelink.*` zone for the service, link it to the virtual
 * network, and add a zone group. Azure then keeps the endpoint's A record
 * in the zone.
 *
 * **Example:** Resolve the blob endpoint privately
 * ```typescript
 * const zone = yield* Azure.PrivateDns.Zone("blob", {
 *   name: "privatelink.blob.core.windows.net",
 * });
 * yield* Azure.PrivateDns.VirtualNetworkLink("blob", {
 *   privateZoneName: zone.privateZoneName,
 *   virtualNetworkId: vnet.virtualNetworkId,
 * });
 * const endpoint = yield* Azure.Network.PrivateEndpoint("files-blob", {
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: account.storageAccountId, groupIds: ["blob"] },
 *   ],
 * });
 * yield* Azure.Network.PrivateDnsZoneGroup("files-blob-dns", {
 *   privateEndpoint: endpoint.privateEndpointName,
 *   privateDnsZoneConfigs: [{ privateDnsZoneId: zone.privateZoneId }],
 * });
 * ```
 *
 * ### Connecting to a Key Vault
 * Key Vault uses the `vault` sub-resource and the
 * `privatelink.vaultcore.azure.net` zone.
 *
 * **Example:** Private vault
 * ```typescript
 * const vault = yield* Azure.KeyVault.Vault("secrets", {
 *   publicNetworkAccess: "Disabled",
 * });
 * const endpoint = yield* Azure.Network.PrivateEndpoint("vault", {
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: vault.vaultId, groupIds: ["vault"] },
 *   ],
 * });
 * const zone = yield* Azure.PrivateDns.Zone("vault", {
 *   name: "privatelink.vaultcore.azure.net",
 * });
 * yield* Azure.PrivateDns.VirtualNetworkLink("vault", {
 *   privateZoneName: zone.privateZoneName,
 *   virtualNetworkId: vnet.virtualNetworkId,
 * });
 * yield* Azure.Network.PrivateDnsZoneGroup("vault-dns", {
 *   privateEndpoint: endpoint.privateEndpointName,
 *   privateDnsZoneConfigs: [{ privateDnsZoneId: zone.privateZoneId }],
 * });
 * ```
 *
 * ### Reaching the Endpoint from an App
 * An app with VNet integration sends its outbound traffic through the
 * virtual network, so the target's FQDN resolves to the private IP
 * through the linked zone. The app's default plan (`B1`) supports VNet
 * integration.
 *
 * **Example:** Web App that reaches a private storage account
 * ```typescript
 * const outbound = yield* Azure.Network.Subnet("web-out", {
 *   virtualNetwork: vnet.virtualNetworkName,
 *   addressPrefix: "10.0.4.0/26",
 *   delegations: [{ serviceName: "Microsoft.Web/serverFarms" }],
 * });
 * const api = yield* Azure.Web.WebApp("Api", {
 *   main: "./src/api.ts",
 *   virtualNetworkSubnetId: outbound.subnetId,
 * });
 * ```
 *
 * ### Static IP Addresses
 * Pin the endpoint's IP when firewalls or clients outside Azure DNS need
 * a fixed address. The address must be free in the subnet.
 *
 * **Example:** Blob endpoint on 10.0.3.10
 * ```typescript
 * const endpoint = yield* Azure.Network.PrivateEndpoint("files-blob", {
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: account.storageAccountId, groupIds: ["blob"] },
 *   ],
 *   ipConfigurations: [
 *     { name: "blob", groupId: "blob", memberName: "blob", privateIpAddress: "10.0.3.10" },
 *   ],
 * });
 * ```
 *
 * ### Manual Approval
 * Use a manual connection when you cannot approve on the target, e.g. a
 * partner's private link service. `connectionStatus` reads `Pending`
 * until the owner approves.
 *
 * **Example:** Connection the target owner approves
 * ```typescript
 * const endpoint = yield* Azure.Network.PrivateEndpoint("partner", {
 *   subnetId: subnet.subnetId,
 *   manualPrivateLinkServiceConnections: [
 *     {
 *       privateLinkServiceId: partnerServiceId,
 *       requestMessage: "Please approve",
 *     },
 *   ],
 * });
 * // endpoint.connectionStatus === "Pending"
 * ```
 *
 * ### Application Security Groups
 * Add the endpoint to an application security group so NSG rules can
 * target it. The subnet needs `privateEndpointNetworkPolicies` set to
 * `"Enabled"` or `"NetworkSecurityGroupEnabled"` for the rules to apply.
 *
 * **Example:** Endpoint in the data tier
 * ```typescript
 * const data = yield* Azure.Network.ApplicationSecurityGroup("data");
 * const endpoint = yield* Azure.Network.PrivateEndpoint("files-blob", {
 *   subnetId: subnet.subnetId,
 *   privateLinkServiceConnections: [
 *     { privateLinkServiceId: account.storageAccountId, groupIds: ["blob"] },
 *   ],
 *   applicationSecurityGroupIds: [data.applicationSecurityGroupId],
 * });
 * ```
 *
 * @resource
 */
export const PrivateEndpoint = GroupedResource<PrivateEndpoint>("Azure.Network.PrivateEndpoint");

type Observed = network.GetPrivateEndpointResponse;

const getEndpoint = (
  subscriptionId: string,
  resourceGroupName: string,
  privateEndpointName: string,
) =>
  orUndefinedIfNotFound(
    network.GetPrivateEndpoint({
      subscriptionId,
      resourceGroupName,
      privateEndpointName,
    }),
  );

const toAttrs = (
  resourceGroup: string,
  name: string,
  endpoint: Observed,
): PrivateEndpoint["Attributes"] => {
  const p = endpoint.properties;
  const connection =
    p?.privateLinkServiceConnections?.[0] ?? p?.manualPrivateLinkServiceConnections?.[0];
  return {
    privateEndpointName: name,
    privateEndpointId: endpoint.id ?? "",
    resourceGroup,
    location: endpoint.location ?? "",
    subnetId: p?.subnet?.id ?? "",
    networkInterfaceIds: (p?.networkInterfaces ?? []).flatMap((nic) =>
      nic.id === undefined ? [] : [nic.id],
    ),
    customDnsConfigs: (p?.customDnsConfigs ?? []).map((config) => ({
      fqdn: config.fqdn,
      ipAddresses: [...(config.ipAddresses ?? [])],
    })),
    connectionStatus: connection?.properties?.privateLinkServiceConnectionState?.status,
    tags: userTags(endpoint.tags),
  };
};

/** Comparable identity of connections (target + group IDs). */
const connectionKey = (connections: ReadonlyArray<PrivateLinkServiceConnectionSpec> | undefined) =>
  canonical(
    (connections ?? [])
      .map((connection) => ({
        target: lower(connection.privateLinkServiceId),
        groups: (connection.groupIds ?? []).map((g) => g.toLowerCase()).sort(),
      }))
      .sort((a, b) => (a.target ?? "").localeCompare(b.target ?? "")),
  );

const toConnections = (
  name: string,
  connections: ReadonlyArray<PrivateLinkServiceConnectionSpec> | undefined,
) =>
  connections?.map((connection) => ({
    name: connection.name ?? name,
    properties: {
      privateLinkServiceId: connection.privateLinkServiceId,
      groupIds: connection.groupIds,
      requestMessage: connection.requestMessage,
    },
  }));

export const PrivateEndpointProvider = () =>
  Provider.succeed(PrivateEndpoint, {
    stables: ["privateEndpointName", "privateEndpointId", "resourceGroup", "location", "subnetId"],

    list: Effect.fn(function* () {
      const { subscriptionId } = yield* AzureEnvironment.current;
      const page = yield* collectAll(network.ListPrivateEndpointBySubscription, { subscriptionId });
      return page.value.flatMap((endpoint) => {
        const group = resourceGroupOf(endpoint.id);
        return hasAnyAlchemyTag(endpoint.tags) && group !== undefined && endpoint.name !== undefined
          ? [toAttrs(group, endpoint.name, endpoint)]
          : [];
      });
    }),

    diff: Effect.fn(function* ({ news, olds, output }) {
      if (!isResolved(news) || output === undefined) return undefined;
      if (
        !sameId(news.resourceGroup, output.resourceGroup) ||
        (news.name !== undefined && !sameId(news.name, output.privateEndpointName)) ||
        (news.location !== undefined && !sameId(news.location, output.location)) ||
        !sameId(news.subnetId, output.subnetId) ||
        (olds !== undefined &&
          (connectionKey(news.privateLinkServiceConnections) !==
            connectionKey(olds.privateLinkServiceConnections) ||
            connectionKey(news.manualPrivateLinkServiceConnections) !==
              connectionKey(olds.manualPrivateLinkServiceConnections) ||
            news.customNetworkInterfaceName !== olds.customNetworkInterfaceName ||
            canonical(news.ipConfigurations ?? []) !== canonical(olds.ipConfigurations ?? [])))
      ) {
        return { action: "replace" } as const;
      }
      return undefined;
    }),

    read: Effect.fn(function* ({ id, olds, output }) {
      const { subscriptionId } = yield* AzureEnvironment.current;
      const resourceGroup = output?.resourceGroup ?? olds?.resourceGroup;
      if (resourceGroup === undefined) return undefined;
      const name = output?.privateEndpointName ?? olds?.name ?? (yield* createNetworkName(id, 64));
      const observed = yield* getEndpoint(subscriptionId, resourceGroup, name);
      if (observed === undefined) return undefined;
      const attrs = toAttrs(resourceGroup, name, observed);
      return (yield* isOwned(id, observed.tags)) ? attrs : Unowned(attrs);
    }),

    reconcile: Effect.fn(function* ({ id, news, output }) {
      const env = yield* AzureEnvironment.current;
      const { subscriptionId } = env;
      yield* ensureRegistered(subscriptionId, "Microsoft.Network");
      const resourceGroup = news.resourceGroup;
      const name = news.name ?? output?.privateEndpointName ?? (yield* createNetworkName(id, 64));
      const location = news.location ?? output?.location ?? env.location;
      const tags = yield* desiredTags(id, news.tags);
      const get = getEndpoint(subscriptionId, resourceGroup, name);

      // Observe.
      let observed = yield* get;

      // Ensure + sync. There is no tags PATCH: tags and application
      // security groups are synced with an idempotent PUT of the same
      // connections.
      if (
        observed === undefined ||
        tagsDiffer(observed.tags, tags) ||
        !sameSet(
          (observed.properties?.applicationSecurityGroups ?? []).flatMap((asg) =>
            asg.id === undefined ? [] : [asg.id],
          ),
          news.applicationSecurityGroupIds,
        )
      ) {
        yield* network
          .PrivateEndpointsCreateOrUpdate({
            subscriptionId,
            resourceGroupName: resourceGroup,
            privateEndpointName: name,
            location,
            tags,
            properties: {
              subnet: { id: news.subnetId },
              privateLinkServiceConnections: toConnections(
                name,
                news.privateLinkServiceConnections,
              ),
              manualPrivateLinkServiceConnections: toConnections(
                name,
                news.manualPrivateLinkServiceConnections,
              ),
              customNetworkInterfaceName: news.customNetworkInterfaceName,
              ipConfigurations: news.ipConfigurations?.map((config) => ({
                name: config.name,
                properties: {
                  groupId: config.groupId,
                  memberName: config.memberName,
                  privateIPAddress: config.privateIpAddress,
                },
              })),
              applicationSecurityGroups: news.applicationSecurityGroupIds?.map((id) => ({ id })),
            },
          })
          .pipe(Effect.retry(whileNetworkBusy));
      }
      observed = yield* waitNetworkProvisioned(`private endpoint ${name}`, get);
      return toAttrs(resourceGroup, name, observed);
    }),

    delete: Effect.fn(function* ({ output }) {
      const { subscriptionId } = yield* AzureEnvironment.current;
      yield* ignoreNotFound(
        network.DeletePrivateEndpoint({
          subscriptionId,
          resourceGroupName: output.resourceGroup,
          privateEndpointName: output.privateEndpointName,
        }),
      ).pipe(Effect.retry(whileNetworkBusy));
      yield* waitNetworkGone(
        `private endpoint ${output.privateEndpointName}`,
        getEndpoint(subscriptionId, output.resourceGroup, output.privateEndpointName),
      );
    }),

    // Delete private endpoints before the subnets they live in.
    nuke: {
      dependsOn: [
        "Azure.Network.VirtualNetwork",
        "Azure.Network.Subnet",
        "Azure.Resources.ResourceGroup",
      ],
    },
  });
