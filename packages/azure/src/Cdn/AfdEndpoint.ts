/** Scope in which the endpoint's generated host-name label can be reused. */
export type AutoGeneratedDomainNameLabelScope =
  | "TenantReuse"
  | "SubscriptionReuse"
  | "ResourceGroupReuse"
  | "NoReuse";

export interface AfdEndpointProps {
  /** Resource group of the profile. Changing it replaces the endpoint. */
  resourceGroup: string;
  /** Front Door profile that holds the endpoint. Changing it replaces the endpoint. */
  profile: string;
  /**
   * Endpoint name: 2-46 letters, digits, and hyphens. Front Door appends a
   * hash and serves it at `<name>-<hash>.<zone>.azurefd.net`. If omitted, a
   * unique name is generated from the app, stage, and logical ID. Changing
   * it replaces the endpoint.
   */
  name?: string;
  /**
   * Whether the endpoint serves traffic.
   * @default "Enabled"
   */
  enabledState?: "Enabled" | "Disabled";
  /**
   * When `Enabled`, only custom domains with mutual TLS can be added to the
   * endpoint's routes.
   * @default "Disabled"
   */
  enforceMtls?: "Enabled" | "Disabled";
  /**
   * Scope in which the generated host-name hash can be reused after the
   * endpoint is deleted: an endpoint with the same name in the same tenant,
   * subscription, or resource group gets the same host name again.
   * `NoReuse` gives every new endpoint a new hash. Changing it replaces the
   * endpoint.
   * @default "TenantReuse"
   */
  autoGeneratedDomainNameLabelScope?: AutoGeneratedDomainNameLabelScope;
  /**
   * User tags. Alchemy ownership tags (`alchemy::stack`, `alchemy::stage`,
   * `alchemy::id`) are merged in automatically.
   * @default {}
   */
  tags?: Record<string, string>;
}

export interface AfdEndpoint extends Resource<
  "Azure.Cdn.AfdEndpoint",
  AfdEndpointProps,
  {
    /** Name of the endpoint. */
    endpointName: string;
    /** ARM resource ID of the endpoint; use it in security policy associations. */
    endpointId: string;
    /** Front Door profile that holds the endpoint. */
    profile: string;
    /** Resource group of the profile. */
    resourceGroup: string;
    /** Public host name, e.g. `app-abc123.z01.azurefd.net`. */
    hostName: string;
    /** Whether the endpoint serves traffic. */
    enabledState: string | undefined;
    /** Host-name label reuse scope. */
    autoGeneratedDomainNameLabelScope: string | undefined;
    /** Edge deployment status (`NotStarted`, `InProgress`, `Succeeded`, `Failed`). */
    deploymentStatus: string | undefined;
    /** User tags (Alchemy ownership tags stripped). */
    tags: Record<string, string>;
  },
  never,
  Providers
> {}

/**
 * An Azure Front Door endpoint (`Microsoft.Cdn/profiles/afdEndpoints`):
 * the `*.azurefd.net` host name clients connect to. Attach routes to send
 * its traffic to origin groups, and custom domains to serve it under your
 * own names.
 *
 * Front Door appends a hash to the endpoint name, so `hostName` looks like
 * `<name>-<hash>.<zone>.azurefd.net`. An endpoint serves nothing until a
 * route links it to an origin group. Endpoints are enabled by default.
 *
 * :::caution[Changing `name`, `profile`, `resourceGroup`, or `autoGeneratedDomainNameLabelScope` replaces the endpoint]
 * Alchemy creates a new endpoint and deletes the old one with its routes.
 * A generated name changes on replacement, so the endpoint gets a new
 * `hostName`: every CNAME that points at the old host name stops working
 * until it follows the new one.
 * :::
 *
 * :::caution[The profile must exist first]
 * Create the profile with `Azure.Cdn.Profile` and pass
 * `profile.profileName`. Free Trial and Azure for Students subscriptions
 * cannot create Front Door profiles.
 * :::
 *
 * @see https://learn.microsoft.com/azure/frontdoor/endpoint
 *
 * ### Creating an Endpoint
 * **Example:** Endpoint on a Front Door profile
 * ```typescript
 * const profile = yield* Azure.Cdn.Profile("cdn");
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 * });
 * // endpoint.hostName → "web-...-abc123.z01.azurefd.net"
 * ```
 *
 * **Example:** Endpoint with a fixed name and tags
 * ```typescript
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 *   name: "contoso-web",
 *   tags: { team: "web" },
 * });
 * ```
 *
 * ### Disabling an Endpoint
 * Set `enabledState: "Disabled"` to stop serving traffic without deleting
 * the endpoint, its routes, or its host name.
 *
 * **Example:** Disabled endpoint
 * ```typescript
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 *   enabledState: "Disabled",
 * });
 * ```
 *
 * ### Keeping the Host Name
 * `autoGeneratedDomainNameLabelScope` decides when a new endpoint with the
 * same name gets the same hash back. With `TenantReuse` (the default), an
 * endpoint you delete and create again under the same `name` keeps its
 * `hostName`. `NoReuse` gives every new endpoint a new hash.
 *
 * **Example:** Stable host name across re-creation
 * ```typescript
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 *   name: "contoso-web",
 *   autoGeneratedDomainNameLabelScope: "TenantReuse",
 * });
 * ```
 *
 * **Example:** Never reuse a host name
 * ```typescript
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 *   autoGeneratedDomainNameLabelScope: "NoReuse",
 * });
 * ```
 *
 * ### Routing Traffic
 * Add an `Azure.Cdn.Route` that links the endpoint to an origin group.
 * The origin group needs an origin before the route deploys.
 *
 * **Example:** Endpoint in front of a Web App
 * ```typescript
 * const api = yield* Azure.Web.WebApp("Api", { main: "./src/api.ts" });
 * const profile = yield* Azure.Cdn.Profile("cdn");
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("web", {
 *   profile: profile.profileName,
 * });
 * const origins = yield* Azure.Cdn.AfdOriginGroup("api", {
 *   profile: profile.profileName,
 * });
 * yield* Azure.Cdn.AfdOrigin("api", {
 *   profile: profile.profileName,
 *   originGroup: origins.originGroupName,
 *   hostName: api.defaultHostName,
 * });
 * yield* Azure.Cdn.Route("default", {
 *   profile: profile.profileName,
 *   endpoint: endpoint.endpointName,
 *   originGroupId: origins.originGroupId,
 * });
 * return { hostName: endpoint.hostName };
 * ```
 *
 * ### Custom Domains
 * Point a CNAME at `endpoint.hostName` and list the domain on a route.
 * At the zone apex, use an alias `A` record set with
 * `targetResourceId: endpoint.endpointId` instead.
 *
 * **Example:** `www` and the apex on one endpoint
 * ```typescript
 * const zone = yield* Azure.Dns.Zone("contoso", { name: "contoso.com" });
 * yield* Azure.Dns.RecordSet("www", {
 *   zoneName: zone.zoneName,
 *   recordType: "CNAME",
 *   name: "www",
 *   cname: endpoint.hostName,
 * });
 * yield* Azure.Dns.RecordSet("apex", {
 *   zoneName: zone.zoneName,
 *   recordType: "A",
 *   name: "@",
 *   targetResourceId: endpoint.endpointId,
 * });
 * ```
 *
 * ### Web Application Firewall
 * Attach a WAF policy to the endpoint through `Azure.Cdn.SecurityPolicy`;
 * `endpoint.endpointId` goes in `domainIds`.
 *
 * **Example:** Protect the endpoint
 * ```typescript
 * const waf = yield* Azure.FrontDoor.WebApplicationFirewallPolicy("waf");
 * yield* Azure.Cdn.SecurityPolicy("waf", {
 *   profile: profile.profileName,
 *   wafPolicyId: waf.policyId,
 *   associations: [{ domainIds: [endpoint.endpointId] }],
 * });
 * ```
 *
 * ### Mutual TLS
 * With `enforceMtls: "Enabled"`, routes on the endpoint accept only custom
 * domains that require client certificates (`mtlsScenario` on
 * `Azure.Cdn.AfdCustomDomain`).
 *
 * **Example:** Endpoint for mTLS-only domains
 * ```typescript
 * const endpoint = yield* Azure.Cdn.AfdEndpoint("partners", {
 *   profile: profile.profileName,
 *   enforceMtls: "Enabled",
 * });
 * ```
 *
 * @resource
 */
export const AfdEndpoint = GroupedResource<AfdEndpoint>("Azure.Cdn.AfdEndpoint");

const createEndpointName = (id: string) => createAfdName(id, 46);

const getEndpoint = (
  subscriptionId: string,
  resourceGroupName: string,
  profileName: string,
  endpointName: string,
) =>
  orUndefinedIfNotFound(
    cdn.GetAFDEndpoint({
      subscriptionId,
      resourceGroupName,
      profileName,
      endpointName,
    }),
  );

const toAttrs = (
  resourceGroup: string,
  profile: string,
  name: string,
  endpoint: cdn.GetAFDEndpointResponse,
): AfdEndpoint["Attributes"] => ({
  endpointName: name,
  endpointId: endpoint.id ?? "",
  profile,
  resourceGroup,
  hostName: endpoint.properties?.hostName ?? "",
  enabledState: endpoint.properties?.enabledState,
  autoGeneratedDomainNameLabelScope: endpoint.properties?.autoGeneratedDomainNameLabelScope,
  deploymentStatus: endpoint.properties?.deploymentStatus,
  tags: userTags(endpoint.tags),
});

export const AfdEndpointProvider = () =>
  Provider.succeed(AfdEndpoint, {
    stables: ["endpointName", "endpointId", "profile", "resourceGroup", "hostName"],

    // Endpoints are deleted with their profile.
    list: Effect.fn(function* () {
      return [];
    }),

    diff: Effect.fn(function* ({ news, output }) {
      if (!isResolved(news) || output === undefined) return undefined;
      if (
        !sameName(news.resourceGroup, output.resourceGroup) ||
        !sameName(news.profile, output.profile) ||
        (news.name !== undefined && !sameName(news.name, output.endpointName)) ||
        (news.autoGeneratedDomainNameLabelScope ?? "TenantReuse") !==
          (output.autoGeneratedDomainNameLabelScope ?? "TenantReuse")
      ) {
        return { action: "replace" } as const;
      }
      return undefined;
    }),

    read: Effect.fn(function* ({ id, olds, output }) {
      const { subscriptionId } = yield* AzureEnvironment.current;
      const resourceGroup = output?.resourceGroup ?? olds?.resourceGroup;
      const profile = output?.profile ?? olds?.profile;
      if (resourceGroup === undefined || profile === undefined) return undefined;
      const name = output?.endpointName ?? olds?.name ?? (yield* createEndpointName(id));
      const observed = yield* getEndpoint(subscriptionId, resourceGroup, profile, name);
      if (observed === undefined) return undefined;
      const attrs = toAttrs(resourceGroup, profile, name, observed);
      return (yield* isOwned(id, observed.tags)) ? attrs : Unowned(attrs);
    }),

    reconcile: Effect.fn(function* ({ id, news, output }) {
      const { subscriptionId } = yield* AzureEnvironment.current;
      yield* ensureRegistered(subscriptionId, "Microsoft.Cdn");
      const { resourceGroup, profile } = news;
      const name = news.name ?? output?.endpointName ?? (yield* createEndpointName(id));
      const tags = yield* desiredTags(id, news.tags);
      const properties = {
        enabledState: news.enabledState ?? "Enabled",
        enforceMtls: news.enforceMtls,
      };
      const where = {
        subscriptionId,
        resourceGroupName: resourceGroup,
        profileName: profile,
        endpointName: name,
      };
      const get = getEndpoint(subscriptionId, resourceGroup, profile, name);
      const label = `Front Door endpoint ${name}`;

      // Observe.
      let observed = yield* get;

      // Ensure.
      if (observed === undefined) {
        yield* cdn
          .CreateAFDEndpoint({
            ...where,
            location: "global",
            tags,
            properties: {
              ...properties,
              autoGeneratedDomainNameLabelScope: news.autoGeneratedDomainNameLabelScope,
            },
          })
          .pipe(Effect.retry(whileProfileBusy));
      }
      observed = yield* waitForAfd(label, get, (e) => e.properties?.provisioningState);

      // Sync tags and mutable properties against observed state.
      const changed = changedFields(properties, observed.properties);
      const tagsChanged = tagsDiffer(observed.tags, tags);
      if (Object.keys(changed).length > 0 || tagsChanged) {
        yield* cdn
          .UpdateAFDEndpoint({
            ...where,
            tags: tagsChanged ? tags : undefined,
            properties: Object.keys(changed).length > 0 ? changed : undefined,
          })
          .pipe(Effect.retry(whileProfileBusy));
        observed = yield* waitForAfd(label, get, (e) => e.properties?.provisioningState);
      }

      return toAttrs(resourceGroup, profile, name, observed);
    }),

    delete: Effect.fn(function* ({ output }) {
      const { subscriptionId } = yield* AzureEnvironment.current;
      yield* ignoreNotFound(
        cdn
          .DeleteAFDEndpoint({
            subscriptionId,
            resourceGroupName: output.resourceGroup,
            profileName: output.profile,
            endpointName: output.endpointName,
          })
          .pipe(Effect.retry(whileProfileBusy)),
      );
      yield* waitUntilGone(
        `Front Door endpoint ${output.endpointName}`,
        getEndpoint(subscriptionId, output.resourceGroup, output.profile, output.endpointName),
        AFD_DELETE_BUDGET,
      );
    }),
  });
