import * as emrc from "@distilled.cloud/aws/emr-containers";
import * as Binding from "alchemy/Binding";
import * as Effect from "effect/Effect";
import * as Layer from "effect/Layer";
import * as AWSBindings from "../AWSBindings.ts";
import { virtualClusterPolicyStatement } from "./BindingHttp.ts";
import type { VirtualCluster } from "./VirtualCluster.ts";

/**
 * Runtime binding for `emr-containers:StartJobRun`.
 *
 * Submits a Spark job run to the bound {@link VirtualCluster}. The virtual
 * cluster ID is injected from the binding; pass a `jobDriver` +
 * `executionRoleArn` + `releaseLabel` directly, or a `jobTemplateId` (+
 * `jobTemplateParameters`) to start from a {@link JobTemplate}. Returns the
 * new job run's `id`/`arn` for use with `DescribeJobRun` / `CancelJobRun`.
 * Provide the implementation with
 * `Effect.provide(AWS.EMRContainers.StartJobRunHttp)`.
 * ### Running Jobs
 * **Example:** Start A Templated Spark Job
 * ```typescript
 * // init — bind the operation to the virtual cluster
 * const startJobRun = yield* AWS.EMRContainers.StartJobRun(virtualCluster);
 *
 * // runtime
 * const { id } = yield* startJobRun({
 *   jobTemplateId: templateId,
 *   jobTemplateParameters: { EntryPoint: "s3://my-bucket/etl.py" },
 * });
 * yield* Effect.log(`job run started: ${id}`);
 * ```
 *
 * @binding
 */
export interface StartJobRun extends Binding.Service<
  StartJobRun,
  "AWS.EMRContainers.StartJobRun",
  (virtualCluster: VirtualCluster) => Effect.Effect<
    (
      request: Omit<emrc.StartJobRunRequest, "virtualClusterId" | "clientToken"> & {
        /**
         * Idempotency token for the job run submission.
         * @default auto-generated per call
         */
        clientToken?: string;
      },
    ) => Effect.Effect<emrc.StartJobRunResponse, emrc.StartJobRunError>
  >
> {}
export const StartJobRun = Binding.Service<StartJobRun>("AWS.EMRContainers.StartJobRun");

export const StartJobRunHttp = Layer.effect(
  StartJobRun,
  Effect.gen(function* () {
    const bind = yield* AWSBindings.Bind;
    const op = yield* AWSBindings.withCredentials(emrc.startJobRun);

    // Bespoke (not the shared builder): `clientToken` is required on the wire
    // schema but auto-generated by the SDK's idempotency-token filling when
    // omitted, so the binding's request keeps it optional.
    return Effect.fn(function* (virtualCluster: VirtualCluster) {
      const VirtualClusterId = yield* virtualCluster.virtualClusterId;
      if (!globalThis.__ALCHEMY_RUNTIME__) {
        yield* bind`AWS.EMRContainers.StartJobRun(${virtualCluster})`({
          policyStatements: [
            virtualClusterPolicyStatement(virtualCluster, ["emr-containers:StartJobRun"]),
          ],
        });
      }
      return Effect.fn(`AWS.EMRContainers.StartJobRun(${virtualCluster.LogicalId})`)(function* (
        request: Omit<emrc.StartJobRunRequest, "virtualClusterId" | "clientToken"> & {
          clientToken?: string;
        },
      ) {
        return yield* op({
          ...request,
          virtualClusterId: yield* VirtualClusterId,
        } as emrc.StartJobRunRequest);
      });
    });
  }),
);
