/**
 * Ownership fallback for STACKIT APIs that have no labels (Object Storage
 * buckets and credentials groups, ...).
 *
 * Core `createPhysicalName` ends every generated name with the resource's
 * instance id in lowercase base32 (`a-z2-7`): `-<16 chars>` when the name
 * fits, or `<8-char hash><16 chars>` (24 chars, no delimiter) when the
 * prefix was truncated. A name with that tail was almost certainly generated
 * by Alchemy, so `list` (used by `alchemy unsafe nuke`) can enumerate it
 * without an ownership label.
 *
 * To keep human-chosen names (`-productionbackups`) out, the tail must also
 * contain at least one of base32's digits (`2-7`). About 3.6% of generated
 * 16-char tails have none and are skipped: nuke under-reports rather than
 * deleting a resource it did not create. Explicitly named resources are
 * never enumerated.
 */
const SHORT_TAIL = /-([a-z2-7]{16})$/;
const TRUNCATED_TAIL = /([a-z2-7]{24})$/;
const HAS_DIGIT = /[2-7]/;

/** Whether `name` has the shape of a name generated by `createPhysicalName`. */
export const isGeneratedPhysicalName = (name: string): boolean => {
  const tail = SHORT_TAIL.exec(name)?.[1] ?? TRUNCATED_TAIL.exec(name)?.[1];
  return tail !== undefined && HAS_DIGIT.test(tail);
};
