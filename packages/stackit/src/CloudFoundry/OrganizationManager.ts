import { Unowned } from "alchemy/AdoptPolicy";
import * as Provider from "alchemy/Provider";
import { Resource } from "alchemy/Resource";
import * as Data from "effect/Data";
import * as Effect from "effect/Effect";
import * as Redacted from "effect/Redacted";
import { resolveProjectScope } from "../IaaS/internal.ts";
import { hasUnresolvedTrigger, triggerProps } from "../internal/diff.ts";
import type { Providers } from "../Providers.ts";
import { getOrgManagerOrUndefined, getPlatformOrUndefined, type ScfScope } from "./internal.ts";

export interface OrganizationManagerProps {
  /** Organization to manage. Changing it replaces the manager. */
  organizationId: string;
  /**
   * Any value. Changing it deletes the manager and creates a new one, with a new user
   * id, username and password: the API can't reset a password. STACKIT only returns a
   * password from the create, so set this on an adopted manager to get a usable
   * `password`. Removing it changes nothing.
   */
  rotationKey?: string;
  /** Project that owns the organization. Changing it replaces the manager. @default the profile's project */
  projectId?: string;
  /** Region of the organization. Changing it replaces the manager. @default the profile's region */
  region?: string;
}

export interface OrganizationManagerAttributes {
  /** Cloud Foundry user id of the manager. Changes when `rotationKey` does. */
  userId: string;
  /** Username of the manager in UAA. Generated by STACKIT. */
  username: string;
  /**
   * The manager's password. `undefined` for a manager Alchemy adopted, until
   * `rotationKey` is set.
   */
  password: Redacted.Redacted<string> | undefined;
  /** The `rotationKey` of the last rotation. */
  rotationKey: string | undefined;
  /** Organization the manager manages. */
  organizationId: string;
  /** Platform the organization is on. */
  platformId: string;
  /** Cloud Foundry v3 API of the platform, for logging in as this manager. */
  apiUrl: string;
  /** Project that owns the organization. */
  projectId: string;
  /** Region of the organization. */
  region: string;
  /** When the manager was created. */
  createdAt: string;
  /** When the manager last changed. */
  updatedAt: string;
}

export type OrganizationManager = Resource<
  "Stackit.CloudFoundry.OrganizationManager",
  OrganizationManagerProps,
  OrganizationManagerAttributes,
  never,
  Providers
>;

/**
 * The organization manager of a STACKIT Cloud Foundry organization: a user with the Org
 * Manager role, and the one credential this API can create. STACKIT generates its
 * username and password. An organization has at most one.
 *
 * `password` is `Redacted`. Pass `apiUrl`, `username` and `password` as the `credentials`
 * of the resources that need the Cloud Foundry API: `Stackit.CloudFoundry.App`, `Route`,
 * `ServiceInstance`, `OrganizationRole` and `SpaceRole`. Org Manager lets it manage users
 * and spaces, and an app also needs `space_developer` in its space, through a `SpaceRole`.
 *
 * The password can't be read back. A manager found without state, which can be a deploy
 * that crashed before saving it, is reported as unowned. Take it over with `--adopt` and
 * set `rotationKey` to get a new one: nothing can hold the old password if it was yours.
 *
 * See [STACKIT's Cloud Foundry docs](https://docs.stackit.cloud/products/runtime/cloud-foundry/).
 *
 * :::caution[Unverified]
 * STACKIT's docs only describe logging in to the Cloud Foundry API with the service
 * accounts of the `space-scoped-service-account` offering. That an organization manager
 * can log in the same way follows from the spec saying it is "backed by a CF user", and
 * hasn't been tried.
 * :::
 *
 * :::caution[Changing `organizationId`, `projectId` or `region` replaces the Manager]
 * Everything using its password needs the new one. When the organization itself is replaced, the
 * old manager stays until what signs in with it is gone. Otherwise it is deleted first.
 * :::
 *
 * ### Creating a Manager
 * **Example:** A manager for an organization
 * ```typescript
 * import * as Stackit from "@alchemy.run/stackit";
 *
 * const organization = yield* Stackit.CloudFoundry.Organization("Org", {});
 * const manager = yield* Stackit.CloudFoundry.OrganizationManager("Manager", {
 *   organizationId: organization.organizationId,
 * });
 * // manager.password is Redacted: hand it to a secret store or a resource, never log it.
 * ```
 *
 * ### Rotating the Password
 * **Example:** Recreate the manager by changing `rotationKey`
 * ```typescript
 * import * as Stackit from "@alchemy.run/stackit";
 *
 * const organization = yield* Stackit.CloudFoundry.Organization("Org", {});
 * const manager = yield* Stackit.CloudFoundry.OrganizationManager("Manager", {
 *   organizationId: organization.organizationId,
 *   rotationKey: "2026-11",
 * });
 * ```
 *
 * ### Deploying with it
 * **Example:** Give the manager the role an app needs
 * ```typescript
 * import * as Stackit from "@alchemy.run/stackit";
 *
 * const organization = yield* Stackit.CloudFoundry.Organization("Org", {});
 * const space = yield* Stackit.CloudFoundry.Space("Dev", {
 *   organizationId: organization.organizationId,
 * });
 * const manager = yield* Stackit.CloudFoundry.OrganizationManager("Manager", {
 *   organizationId: organization.organizationId,
 * });
 * yield* Stackit.CloudFoundry.SpaceRole("Deployer", {
 *   organizationId: organization.organizationId,
 *   spaceId: space.spaceId,
 *   type: "space_developer",
 *   userGuid: manager.userId,
 *   credentials: {
 *     apiUrl: manager.apiUrl,
 *     username: manager.username,
 *     password: manager.password,
 *   },
 * });
 * ```
 *
 * A manager with another id, found once this resource has one in state, is someone else's. The
 * deploy fails with `Stackit.CloudFoundry.OrganizationManagerNotOurs` and leaves it alone. Delete
 * it, or set a new `rotationKey` to replace it.
 *
 * @resource
 * @product STACKIT Cloud Foundry
 * @category CloudFoundry
 */
export const OrganizationManager = Resource<OrganizationManager>(
  "Stackit.CloudFoundry.OrganizationManager",
);

/** The organization has a manager this resource didn't make, and it was left alone. */
export class OrganizationManagerNotOurs extends Data.TaggedError(
  "Stackit.CloudFoundry.OrganizationManagerNotOurs",
)<{
  readonly organizationId: string;
  readonly userId: string;
  readonly message: string;
}> {}

/** Idempotent: 404 and 410 mean gone, and the API answers 410 even if there never was one. */
const deleteManager = (scope: ScfScope, organizationId: string) =>
  scf.deleteOrgManager({ ...scope, organizationId }).pipe(
    Effect.asVoid,
    Effect.catchTag(["NotFound", "OrgManagerGone"], () => Effect.void),
  );

const toAttrs = (
  manager: scf.OrgManager,
  apiUrl: string | undefined,
  secret: Pick<OrganizationManagerAttributes, "password" | "rotationKey">,
): OrganizationManagerAttributes => ({
  userId: manager.guid,
  username: manager.username,
  password: secret.password,
  rotationKey: secret.rotationKey,
  organizationId: manager.orgId,
  platformId: manager.platformId,
  apiUrl: apiUrl ?? "",
  projectId: manager.projectId,
  region: manager.region,
  createdAt: manager.createdAt,
  updatedAt: manager.updatedAt,
});

const apiUrlOf = (scope: ScfScope, platformId: string) =>
  getPlatformOrUndefined(scope, platformId).pipe(Effect.map((platform) => platform?.apiUrl));

/**
 * The create runs several non-atomic steps, and the spec says a failure needs the delete
 * before a retry. A request the API refused ran none of them, and may have been refused because a
 * manager someone else made got there first, so only a failure that isn't a refusal cleans up.
 */
const createManager = (scope: ScfScope, organizationId: string) =>
  scf.createOrgManager({ ...scope, organizationId }).pipe(
    Effect.tapError((error) =>
      error._tag === "BadRequest" ||
      error._tag === "Conflict" ||
      error._tag === "Forbidden" ||
      error._tag === "NotFound"
        ? Effect.void
        : deleteManager(scope, organizationId).pipe(Effect.ignore),
    ),
    Effect.map((created) => ({
      manager: created as scf.OrgManager,
      password: Redacted.isRedacted(created.password)
        ? created.password
        : Redacted.make(created.password),
    })),
  );

export const OrganizationManagerProvider = () =>
  Provider.succeed(OrganizationManager, {
    stables: ["organizationId", "platformId", "projectId", "region"],
    nuke: { dependsOn: ["Stackit.CloudFoundry.Organization"] },

    // An organization's delete takes its manager with it, or fails with what is left.
    // A manager carries no marker of who made it, so nuke can't tell whose it is.
    list: () => Effect.succeed([]),

    diff: Effect.fn(function* ({ news, output }) {
      if (output === undefined) return undefined;
      // There is only one manager per organization, so a change of scope can't leave the old one.
      if (hasUnresolvedTrigger<OrganizationManagerProps>(news, ["projectId", "region"])) {
        return { action: "replace", deleteFirst: true } as const;
      }
      // An organization's id is stable, so an unresolved one is an organization being replaced,
      // and a new organization has no manager yet. The old manager stays until garbage collection,
      // after everything that signs in with it: an old app, route, service instance or role can't
      // be deleted once its login is gone.
      if (hasUnresolvedTrigger<OrganizationManagerProps>(news, ["organizationId"])) {
        return { action: "replace", deleteFirst: false } as const;
      }
      const resolved = triggerProps<OrganizationManagerProps>(news);
      const scope = yield* resolveProjectScope(resolved, undefined);
      if (
        resolved.organizationId !== output.organizationId ||
        scope.projectId !== output.projectId ||
        scope.region !== output.region
      ) {
        return {
          action: "replace",
          deleteFirst: resolved.organizationId === output.organizationId,
        } as const;
      }
      return undefined;
    }),

    read: Effect.fn(function* ({ olds, output, previous }) {
      const scope = yield* resolveProjectScope(olds, output);
      const organizationId = output?.organizationId ?? olds?.organizationId;
      if (organizationId === undefined) return undefined;
      const manager = yield* getOrgManagerOrUndefined(scope, organizationId);
      if (manager === undefined) return undefined;
      const apiUrl = yield* apiUrlOf(scope, manager.platformId);
      const attrs = toAttrs(manager, apiUrl, {
        password: output?.userId === manager.guid ? output.password : undefined,
        rotationKey: output?.userId === manager.guid ? output.rotationKey : undefined,
      });
      // The API has no marker of who made it, and its password can't be read back.
      const ours =
        output?.userId === manager.guid ||
        (previous?.userId === manager.guid &&
          previous.organizationId === organizationId &&
          previous.projectId === scope.projectId &&
          previous.region === scope.region);
      return ours ? attrs : Unowned(attrs);
    }),

    reconcile: Effect.fn(function* ({ news, output }) {
      const scope = yield* resolveProjectScope(news, output);
      const organizationId = news.organizationId;
      // `output` only speaks for this organization's manager.
      const known =
        output?.organizationId === organizationId &&
        output.projectId === scope.projectId &&
        output.region === scope.region
          ? output
          : undefined;

      // 1. Observe
      let manager = yield* getOrgManagerOrUndefined(scope, organizationId);
      const isKnown = manager !== undefined && manager.guid === known?.userId;
      let password = isKnown ? known?.password : undefined;
      let rotationKey = isKnown ? known?.rotationKey : undefined;

      // A new key asks for a rotation. That also takes over a manager with another id, because
      // the rotation before this one may have crashed after its create. Anything else with
      // another id is someone else's: it isn't deleted, and its password can't be known.
      const rotate =
        known !== undefined &&
        news.rotationKey !== undefined &&
        news.rotationKey !== known.rotationKey;
      if (manager !== undefined && !isKnown && !rotate) {
        return yield* new OrganizationManagerNotOurs({
          organizationId,
          userId: manager.guid,
          message: `Organization ${organizationId} has manager ${manager.guid}, which this stack didn't create, and it was left alone. Delete it to have a new one created, or set a new rotationKey on a deployed manager to replace it.`,
        });
      }

      // Rotate by recreating: the API can't reset a password.
      if (manager !== undefined && rotate) {
        yield* deleteManager(scope, organizationId);
        manager = undefined;
      }

      // 2. Ensure. The response holds the only copy of the password.
      if (manager === undefined) {
        const created = yield* createManager(scope, organizationId);
        manager = created.manager;
        password = created.password;
        rotationKey = news.rotationKey;
      }

      // Existence-only: nothing else about a manager can change.
      const apiUrl = yield* apiUrlOf(scope, manager.platformId);
      return toAttrs(manager, apiUrl, {
        password,
        rotationKey,
      });
    }),

    delete: Effect.fn(function* ({ output }) {
      // Only the manager this resource created: an unrelated one it never held the
      // password of may have replaced it.
      const scope = { projectId: output.projectId, region: output.region };
      const live = yield* getOrgManagerOrUndefined(scope, output.organizationId);
      if (live !== undefined && live.guid !== output.userId) return;
      yield* deleteManager(scope, output.organizationId);
    }),
  });
