/**
 * Modal object names: letters, digits, `-`, `.` and `_`, shorter than 64
 * characters. Names are unique per environment and kind.
 */
export const objectName = (id: string, name: string | undefined, maxLength = 63) =>
  name !== undefined ? Effect.succeed(name) : createPhysicalName({ id, maxLength, delimiter: "-" });

/**
 * The environment a Modal call targets. Modal resolves an empty name to the
 * workspace's default environment, so `undefined` stays `""` on the wire and
 * `undefined` in attributes.
 */
export const environmentOf = (name: string | undefined): string => name ?? "";

/** Seconds of a duration given as seconds or a `"10 minutes"`-style string. */
export const seconds = (value: number | string | undefined): number | undefined => {
  if (value === undefined) return undefined;
  if (typeof value === "number") return value;
  const match =
    /^\s*(\d+(?:\.\d+)?)\s*(ms|millis|milliseconds?|s|secs?|seconds?|m|mins?|minutes?|h|hours?)\s*$/i.exec(
      value,
    );
  if (!match) return Number(value);
  const n = Number(match[1]);
  const unit = match[2]!.toLowerCase();
  if (unit.startsWith("ms") || unit.startsWith("milli")) return n / 1000;
  if (unit.startsWith("h")) return n * 3600;
  if (unit.startsWith("m")) return n * 60;
  return n;
};

/**
 * Every item of a Modal `List*` call. Modal pages by creation time: each
 * request takes `maxObjects` and `createdBefore`, the creation time of the
 * oldest item seen so far.
 */
export const listAll: <T, E, R>(
  fetch: (pagination: ListPagination) => Effect.Effect<ReadonlyArray<T>, E, R>,
  createdAt: (item: T) => number | undefined,
  pageSize?: number,
) => Effect.Effect<T[], E, R> = Effect.fn(function* <T, E, R>(
  fetch: (pagination: ListPagination) => Effect.Effect<ReadonlyArray<T>, E, R>,
  createdAt: (item: T) => number | undefined,
  pageSize = 100,
) {
  const all: T[] = [];
  let before: number | undefined;
  for (let page = 0; page < 1_000; page++) {
    const items = yield* fetch({ maxObjects: pageSize, createdBefore: before });
    all.push(...items);
    if (items.length < pageSize) break;
    const oldest = Math.min(...items.map((item) => createdAt(item) ?? Number.POSITIVE_INFINITY));
    if (!Number.isFinite(oldest) || oldest === before) break;
    before = oldest;
  }
  return all;
});

/**
 * The names of every environment in the workspace, for `list` operations that
 * enumerate objects across environments.
 */
export const environmentNames = Effect.gen(function* () {
  const response = yield* environment.listEnvironment({});
  return (response.items ?? []).flatMap((item) => (item.name ? [item.name] : []));
});

/** A wire `map<string, string>` without the absent entries proto3 JSON allows. */
export const stringMap = (
  map: Readonly<Record<string, string | undefined>> | undefined,
): Record<string, string> =>
  Object.fromEntries(
    Object.entries(map ?? {}).flatMap(([key, value]) =>
      value === undefined ? [] : [[key, value]],
    ),
  );

/**
 * Whether a name was generated by `createPhysicalName` (it ends in a
 * 16-character base32 instance suffix, or an 8-character truncation hash plus
 * the suffix). Modal objects other than Apps and Sandboxes have no tags, so
 * `list` (and `alchemy nuke`) only enumerate objects with generated names
 * and the objects runtimes created (`isRuntimeName`); objects given an
 * explicit `name` are never swept.
 */
export const isGeneratedName = (name: string | undefined): boolean =>
  name !== undefined && /-[a-z2-7]{16}$/.test(name);

/**
 * An environment by name, or a `Modal.Environment` (yielded: `yield* Agents`)
 * whose name is used.
 */
export type EnvironmentInput = string | { readonly name: string };

/** The environment name an {@link EnvironmentInput} resolved to. */
export const envNameOf = (value: unknown): string | undefined =>
  typeof value === "string"
    ? value || undefined
    : typeof value === "object" &&
        value !== null &&
        "name" in value &&
        typeof value.name === "string"
      ? value.name
      : undefined;

/** A protobuf `Timestamp` (RFC 3339) for a `Date`, ISO string or epoch milliseconds. */
export const timestampOf = (value: Date | string | number): string =>
  typeof value === "string" ? value : new Date(value).toISOString();

/**
 * Resolve a record of distilled operations into their call functions, like
 * `Effect.all` over Effects. An operation is yieldable (`yield* op` captures
 * the current context and returns a requirement-free call) but isn't an
 * Effect value at runtime, so `Effect.all({ put: queue.putQueue })` fails.
 *
 * @example
 * ```ts
 * const QueueOps = operations({ put: queue.putQueue, get: queue.getQueue });
 * const { put } = yield* ModalBindings.withCredentials(QueueOps);
 * ```
 */
export const operations = <
  const Ops extends Record<string, Effect.Effect<unknown, never, OperationServices>>,
>(
  ops: Ops,
): Effect.Effect<{ readonly [K in keyof Ops]: Effect.Success<Ops[K]> }, never, OperationServices> =>
  Effect.gen(function* () {
    const resolved: Record<string, unknown> = {};
    for (const [key, op] of Object.entries(ops)) resolved[key] = yield* op;
    return resolved as { readonly [K in keyof Ops]: Effect.Success<Ops[K]> };
  });

/** The error of a resolved distilled call (or any function returning an Effect). */
export type ErrorOf<F> = F extends (...args: any[]) => Effect.Effect<any, infer E, any> ? E : never;

/** The error of operation `K` of a resolved operations record. */
export type OpError<Ops, K extends keyof Ops> = ErrorOf<Ops[K]>;

/** What a distilled Modal operation needs to run: credentials and an HTTP client. */
export type OperationServices = Credentials | HttpClient.HttpClient;
