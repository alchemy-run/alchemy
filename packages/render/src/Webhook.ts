import { Unowned } from "alchemy/AdoptPolicy";
import { isResolved } from "alchemy/Diff";
import { createPhysicalName } from "alchemy/PhysicalName";
import * as Provider from "alchemy/Provider";
import { Resource } from "alchemy/Resource";
import * as Effect from "effect/Effect";
import * as Redacted from "effect/Redacted";
import * as Client from "./internal/Client.ts";
import { toRedacted } from "./internal/Redacted.ts";
import type { WireWebhook } from "./internal/WireTypes.ts";
import type { Providers } from "./Providers.ts";

export interface WebhookProps {
  /** Webhook display name. If omitted, a deterministic physical name is generated. */
  name?: string;
  /** Optional Render workspace/owner ID. Defaults to the configured profile or the sole owner on `/owners`. */
  ownerId?: string;
  /** HTTPS destination URL that receives signed webhook events. */
  url: string;
  /** Whether webhook deliveries are enabled. Defaults to `true`. */
  enabled?: boolean;
  /** Event types that trigger deliveries (empty array delivers all event types). */
  eventFilter?: string[];
}

export interface WebhookAttributes {
  /** Render webhook ID (`whk-...`). */
  id: string;
  /** Webhook name. */
  name: string;
  /** Webhook destination URL. */
  url: string;
  /** Whether webhook deliveries are active. */
  enabled: boolean;
  /** Configured event type filters. */
  eventFilter: string[];
  /** Signing secret generated by Render for HMAC signature verification (redacted). */
  secret: Redacted.Redacted<string>;
}

export interface WebhookLookup {
  /** Look up an existing webhook by ID (`whk-...`). */
  id?: string;
  /** Look up an existing webhook by exact name. */
  name?: string;
  /** Optional owner ID override for name lookup. */
  ownerId?: string;
}

export type Webhook = Resource<
  "Render.Webhook",
  WebhookProps,
  WebhookAttributes,
  never,
  Providers,
  WebhookLookup
>;

/**
 * A Render Webhook subscribes an HTTPS endpoint to deploy, build, disk, and
 * database lifecycle events with HMAC request signing.
 *
 * **Example:** Subscribe to deploy completion events
 * ```typescript
 * const hook = yield* Render.Webhook("DeployEvents", {
 *   name: "deploy-events",
 *   url: "https://hooks.example.com/render",
 *   enabled: true,
 *   eventFilter: ["deploy_ended", "build_ended"],
 * });
 * ```
 *
 * @resource
 * @product Observability & Events
 * @category Observability & Events
 */
export const Webhook = Resource<Webhook>("Render.Webhook");

const mapWebhook = (w: WireWebhook): WebhookAttributes => ({
  id: w.id,
  name: w.name,
  url: w.url,
  enabled: w.enabled,
  eventFilter: w.eventFilter ?? [],
  secret: toRedacted(w.secret),
});

export const WebhookProvider = () =>
  Provider.effect(
    Webhook,
    Effect.succeed({
      stables: ["id", "secret"],
      diff: Effect.fn(function* ({ news }) {
        if (!isResolved(news)) return undefined;
        return undefined;
      }),
      read: Effect.fn(function* ({ id, olds, output, previous }) {
        if (output?.id) {
          const w = yield* Client.ignoreNotFound(Client.getWebhook(output.id));
          return w ? mapWebhook(w) : undefined;
        }
        const explicitName =
          typeof olds?.name === "string" && olds.name.length > 0 ? olds.name : undefined;
        const explicitOwnerId =
          typeof olds?.ownerId === "string" && olds.ownerId.length > 0 ? olds.ownerId : undefined;
        const desiredName = explicitName ?? (yield* createPhysicalName({ id, maxLength: 64 }));
        const ownerId = yield* Client.resolveOwnerId(explicitOwnerId);
        const all = yield* Client.listWebhooks({ ownerId: [ownerId] });
        const matched = all.find((w) => w.name === desiredName);
        if (!matched) return undefined;
        const attrs = mapWebhook(matched);
        return explicitName === undefined || matched.id === previous?.id ? attrs : Unowned(attrs);
      }),
      lookup: Effect.fn(function* (props) {
        if (props.id) {
          const w = yield* Client.ignoreNotFound(Client.getWebhook(props.id));
          return w ? mapWebhook(w) : undefined;
        }
        if (props.name) {
          const ownerId = yield* Client.resolveOwnerId(props.ownerId);
          const all = yield* Client.listWebhooks({ ownerId: [ownerId] });
          const matched = all.find((w) => w.name === props.name);
          return matched ? mapWebhook(matched) : undefined;
        }
        return undefined;
      }),
      list: Effect.fn(function* () {
        const ownerId = yield* Client.resolveOwnerId();
        const all = yield* Client.listWebhooks({ ownerId: [ownerId] });
        return all.map(mapWebhook);
      }),
      reconcile: Effect.fn(function* ({ id, news, output }) {
        const desiredName = news.name ?? (yield* createPhysicalName({ id, maxLength: 64 }));
        const existing = output?.id
          ? yield* Client.ignoreNotFound(Client.getWebhook(output.id))
          : undefined;

        if (!existing) {
          const ownerId = yield* Client.resolveOwnerId(news.ownerId);
          const created = yield* Client.createWebhook({
            ownerId,
            name: desiredName,
            url: news.url,
            enabled: news.enabled ?? true,
            eventFilter: news.eventFilter ?? [],
          });
          return mapWebhook(created);
        }

        const updated = yield* Client.updateWebhook(existing.id, {
          name: desiredName,
          url: news.url,
          enabled: news.enabled ?? true,
          eventFilter: news.eventFilter ?? [],
        });
        return mapWebhook(updated);
      }),
      delete: Effect.fn(function* ({ output }) {
        if (!output?.id) return;
        yield* Client.deleteWebhook(output.id);
      }),
    }),
  );
