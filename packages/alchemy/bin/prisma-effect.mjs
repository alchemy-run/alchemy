#!/usr/bin/env node
// Prisma generator emitting effect/Schema definitions for every model and
// enum in the datamodel. Declared in schema.prisma as:
//
//   generator effect {
//     provider = "alchemy-prisma-effect"
//     output   = "./effect.ts"
//   }
//
// `Prisma.Schema` injects this generator automatically (see
// src/Prisma/Schema.ts), so most users never write the block by hand.
//
// Self-contained plain JS on purpose: the bin must run under `node` from
// both the published package and the repo checkout, without a build step.
import helper from "@prisma/generator-helper";
import fs from "node:fs";
import path from "node:path";

/** Prisma scalar → effect/Schema (v4) expression. */
const SCALARS = {
  String: "Schema.String",
  Int: "Schema.Int",
  Float: "Schema.Number",
  Boolean: "Schema.Boolean",
  BigInt: "Schema.BigInt",
  DateTime: "Schema.Date",
  Bytes: "Schema.Uint8Array",
  // Precision-safe: driver adapters surface Decimal columns as strings.
  Decimal: "Schema.String",
  Json: "Schema.Unknown",
};

const fieldSchema = (field, enumNames) => {
  let base;
  if (field.kind === "enum" && enumNames.has(field.type)) {
    base = field.type;
  } else if (field.kind === "scalar" && SCALARS[field.type]) {
    base = SCALARS[field.type];
  } else {
    return undefined; // relations (kind "object") and unsupported types
  }
  if (field.isList) base = `Schema.Array(${base})`;
  // Prisma clients surface missing optionals as null, not undefined.
  if (!field.isRequired) base = `Schema.NullOr(${base})`;
  return base;
};

export const generate = (dmmf) => {
  const enums = dmmf.datamodel.enums ?? [];
  const models = dmmf.datamodel.models ?? [];
  const enumNames = new Set(enums.map((e) => e.name));

  const lines = [
    "// Generated by alchemy-prisma-effect. Do not edit.",
    "//",
    "// effect/Schema definitions for every Prisma model and enum — decode",
    "// rows read outside the Prisma client (raw SQL, sync engines, queues)",
    "// or reuse the shapes in RPC and HTTP contracts.",
    `import * as Schema from "effect/Schema";`,
    "",
  ];

  for (const e of enums) {
    const literals = e.values.map((v) => JSON.stringify(v.name)).join(", ");
    lines.push(
      `export const ${e.name} = Schema.Literals([${literals}]);`,
      `export type ${e.name} = typeof ${e.name}.Type;`,
      "",
    );
  }

  for (const model of models) {
    const fields = model.fields
      .map((field) => {
        const schema = fieldSchema(field, enumNames);
        return schema === undefined ? undefined : `  ${field.name}: ${schema},`;
      })
      .filter((line) => line !== undefined);
    lines.push(
      `export const ${model.name} = Schema.Struct({`,
      ...fields,
      `});`,
      `export type ${model.name} = typeof ${model.name}.Type;`,
      "",
    );
  }

  return lines.join("\n");
};

helper.generatorHandler({
  onManifest() {
    return {
      prettyName: "Alchemy Effect Schemas",
      defaultOutput: "./effect.ts",
    };
  },
  async onGenerate(options) {
    // Prisma absolutizes `output` against the schema directory before
    // invoking the generator; fall back defensively for older CLIs.
    const raw = options.generator.output?.value ?? "./effect.ts";
    const resolved = path.isAbsolute(raw)
      ? raw
      : path.resolve(path.dirname(options.schemaPath), raw);
    // Accept both a file (ending in .ts) and a directory output.
    const file = resolved.endsWith(".ts")
      ? resolved
      : path.join(resolved, "index.ts");
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, generate(options.dmmf));
  },
});
