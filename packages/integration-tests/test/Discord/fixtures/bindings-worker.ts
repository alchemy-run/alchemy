// `POST /<Binding>` calls the binding with the JSON body as its request.
// Failures answer 200 with `{ error: { _tag } }` so tests can assert typed tags.
export default class DiscordBindingsWorker extends Cloudflare.Worker<DiscordBindingsWorker>()(
  "DiscordBindingsWorker",
  { main: import.meta.url },
  Effect.gen(function* () {
    const bindings = yield* bindAll;
    return {
      fetch: Effect.gen(function* () {
        const request = yield* HttpServerRequest;
        const name = new URL(request.url, "http://worker").pathname.slice(1);
        const binding = bindings[name];
        if (binding === undefined || request.method !== "POST") {
          return HttpServerResponse.text("ok");
        }
        const body = yield* request.json;
        const result = yield* binding(body).pipe(
          Effect.map((data) => ({ data })),
          Effect.catch((error) =>
            Effect.succeed({
              error: {
                _tag: error._tag,
                message: String((error as { message?: unknown }).message ?? ""),
              },
            }),
          ),
        );
        return yield* HttpServerResponse.json(result);
      }).pipe(Effect.orDie),
    };
  }).pipe(Effect.provide(BindingsHttp)),
) {}
