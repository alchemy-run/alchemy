import { createPhysicalName } from "alchemy/PhysicalName";
import { Stack } from "alchemy/Stack";
import { Stage } from "alchemy/Stage";
/**
 * Naming and ownership helpers shared by every E2B resource and binding.
 *
 * E2B has metadata only on secrets and sandboxes. Templates, snapshots,
 * volumes, webhooks and API keys carry nothing but a name, so a resource
 * whose name the engine generated (stack, stage, logical id, instance
 * suffix) is recognised as ours by that name; an explicit, user-chosen name
 * found without prior state is reported `Unowned`.
 */
import { createInternalTags } from "alchemy/Tags";
import * as Effect from "effect/Effect";

/** E2B names: letters, digits, `-` and `_`. Lowercased (secrets and templates are lowercased by E2B). */
export const e2bName = (id: string, name: string | undefined, maxLength = 64) =>
  name !== undefined
    ? Effect.succeed(name)
    : createPhysicalName({ id, lowercase: true, maxLength, delimiter: "-" });

/**
 * Whether a name looks generated by `createPhysicalName` (lowercase, ending
 * in a base32 instance suffix). Used by `list` to report only resources
 * Alchemy created, for nuke.
 */
export const isGeneratedName = (name: string | undefined): boolean =>
  name !== undefined && /^[a-z0-9][a-z0-9_-]*-[a-z2-7]{8,16}$/.test(name);

/** The `alchemy::stack` / `alchemy::stage` / `alchemy::id` stamp for metadata maps. */
export const ownershipMetadata = (id: string) => createInternalTags(id);

/**
 * The stamp runtime-created objects carry: the stack and stage that created
 * them and the binding's logical id. Destroy sweeps by it.
 */
export const runtimeMetadata = Effect.fn(function* (bindingId: string) {
  const stack = yield* Stack;
  const stage = yield* Stage;
  return {
    "alchemy::stack": stack.name,
    "alchemy::stage": stage,
    "alchemy::binding": bindingId,
  } as Record<string, string>;
});

/** Whether a metadata map carries this resource's ownership stamp. */
export const hasOwnershipMetadata = Effect.fn(function* (
  id: string,
  metadata: Readonly<Record<string, string>> | null | undefined,
) {
  const expected = yield* createInternalTags(id);
  return Object.entries(expected).every(([key, value]) => metadata?.[key] === value);
});

/** Whether a metadata map was stamped by any Alchemy stack (for nuke). */
export const hasAnyAlchemyMetadata = (
  metadata: Readonly<Record<string, string>> | null | undefined,
): boolean => metadata !== undefined && metadata !== null && "alchemy::stack" in metadata;

/** User metadata with the internal `alchemy::*` keys removed. */
export const userMetadata = (
  metadata: Readonly<Record<string, string>> | null | undefined,
): Record<string, string> =>
  Object.fromEntries(
    Object.entries(metadata ?? {}).filter(([key]) => !key.startsWith("alchemy::")),
  );
