/**
 * Generate the code mode runtimes shipped as source strings:
 *
 * - `src/internal/codemode-effect.generated.ts`: the effect modules that
 *   `Pi.CodeModeEffect` scripts get in scope, as one script that assigns
 *   them to `__alchemyEffect`. It is prepended to every script, so it runs
 *   inside the QuickJS VM wherever the VM runs.
 * - `src/internal/codemode-isolate.generated.ts`: the main module of the
 *   isolate `PiCloudflare.EvalWorkerLoader` loads, which runs the VM with
 *   `serveCodemodeRemote`.
 *
 * Run after bumping `effect` or `@earendil-works/pi-codemode`:
 *
 *     bun scripts/generate-codemode.ts
 *
 * `--check` fails when a generated file was built from other versions.
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { rolldown } from "rolldown";

const root = resolve(import.meta.dirname, "..");
const require = createRequire(join(root, "package.json"));
const versionOf = (name: string) =>
  (JSON.parse(readFileSync(require.resolve(`${name}/package.json`), "utf8")) as { version: string })
    .version;

const effectVersion = versionOf("effect");
const codemodeVersion = versionOf("@earendil-works/pi-codemode");

/**
 * What a script has in scope: effect modules under their own names, except
 * those that would shadow a JavaScript global (`Array`, `String`, `Number`,
 * `Function`), which get effect's usual short names or export their helpers.
 */
const EFFECT_SCOPE: ReadonlyArray<readonly [name: string, module: string]> = [
  ["Arr", "Array"],
  ["BigDecimal", "BigDecimal"],
  ["Cause", "Cause"],
  ["Chunk", "Chunk"],
  ["Data", "Data"],
  ["Duration", "Duration"],
  ["Effect", "Effect"],
  ["Equal", "Equal"],
  ["Exit", "Exit"],
  ["HashMap", "HashMap"],
  ["HashSet", "HashSet"],
  ["Match", "Match"],
  ["Num", "Number"],
  ["Option", "Option"],
  ["Order", "Order"],
  ["Predicate", "Predicate"],
  ["Record", "Record"],
  ["Result", "Result"],
  ["Schedule", "Schedule"],
  ["Str", "String"],
  ["Struct", "Struct"],
];
const FUNCTIONS = ["pipe", "flow", "identity"];
const EFFECT_NAMES = [...EFFECT_SCOPE.map(([name]) => name), ...FUNCTIONS];

const effectFile = join(root, "src/internal/codemode-effect.generated.ts");
const isolateFile = join(root, "src/internal/codemode-isolate.generated.ts");
const stamp = `effect@${effectVersion}, @earendil-works/pi-codemode@${codemodeVersion}`;

if (process.argv.includes("--check")) {
  const stale = [effectFile, isolateFile].filter(
    (file) => !existsSync(file) || !readFileSync(file, "utf8").includes(stamp),
  );
  if (stale.length > 0) {
    console.error(`stale: ${stale.join(", ")}. Run bun scripts/generate-codemode.ts`);
    process.exit(1);
  }
  process.exit(0);
}

const bundle = async (
  entry: string,
  options: { format: "esm" | "iife"; name?: string; external?: string[] },
) => {
  const input = join(root, `.generate-${options.format}.js`);
  writeFileSync(input, entry);
  try {
    const build = await rolldown({
      input,
      platform: "browser",
      treeshake: true,
      external: options.external,
    });
    const { output } = await build.generate({
      format: options.format,
      minify: true,
      ...(options.name ? { name: options.name } : {}),
    });
    return output.map((chunk) => ("code" in chunk ? chunk.code : "")).join("");
  } finally {
    rmSync(input, { force: true });
  }
};

const header = (what: string) =>
  [
    `// AUTO-GENERATED by scripts/generate-codemode.ts. DO NOT EDIT.`,
    `// ${what}, from ${stamp}.`,
    ``,
  ].join("\n");

const effect = await bundle(
  [
    ...EFFECT_SCOPE.map(([name, module]) => `export * as ${name} from "effect/${module}";`),
    `export { ${FUNCTIONS.join(", ")} } from "effect/Function";`,
  ].join("\n"),
  { format: "iife", name: "__alchemyEffect" },
);
writeFileSync(
  effectFile,
  [
    header("The effect modules in scope of a Pi.CodeModeEffect script"),
    `/** The names a script has in scope: the members of \`__alchemyEffect\`. */`,
    `export const EFFECT_NAMES: ReadonlyArray<string> = ${JSON.stringify(EFFECT_NAMES)};`,
    ``,
    `/** A script that declares \`var __alchemyEffect\`, one namespace per module. */`,
    `export const EFFECT_RUNTIME: string = ${JSON.stringify(effect)};`,
    ``,
  ].join("\n"),
);

const isolate = await bundle(
  [
    `import { WorkerEntrypoint } from "cloudflare:workers";`,
    `import { serveCodemodeRemote } from "@earendil-works/pi-codemode/portable";`,
    `import wasm from "./quickjs.wasm";`,
    `export default class CodemodeIsolate extends WorkerEntrypoint {`,
    `  execute(request, exchange) {`,
    `    return serveCodemodeRemote(request, exchange, {`,
    `      wasm,`,
    `      maxInterruptBudget: this.env.MAX_INTERRUPT_BUDGET,`,
    `      maxMemoryLimitBytes: this.env.MAX_MEMORY_LIMIT_BYTES,`,
    `    });`,
    `  }`,
    `}`,
  ].join("\n"),
  { format: "esm", external: ["cloudflare:workers", "./quickjs.wasm"] },
);
writeFileSync(
  isolateFile,
  [
    header("The main module of the isolate PiCloudflare.EvalWorkerLoader loads"),
    `/** Imports \`./quickjs.wasm\`; its default entrypoint serves \`RemoteCodemodeSandbox\`. */`,
    `export const ISOLATE_MODULE: string = ${JSON.stringify(isolate)};`,
    ``,
    `/** Names the isolate in the loader's cache, so a new build loads a new isolate. */`,
    `export const ISOLATE_VERSION = ${JSON.stringify(`pi-codemode-${codemodeVersion}`)};`,
    ``,
  ].join("\n"),
);

console.log(
  `effect runtime ${(effect.length / 1024).toFixed(0)}KB, isolate ${(isolate.length / 1024).toFixed(0)}KB (${stamp})`,
);
