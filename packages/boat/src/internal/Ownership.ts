/**
 * Naming and ownership helpers shared by every Boat resource and binding.
 *
 * Boat sandboxes carry labels, set once at create. Label keys can't hold
 * `:`, so Alchemy's `alchemy::stack` / `alchemy::stage` / `alchemy::id`
 * ownership tags are written as `alchemy.stack` / `alchemy.stage` /
 * `alchemy.id`. Environments, snapshots, webhooks and API keys carry only a
 * name, so a resource whose name the engine generated is recognised as ours
 * by that name; an explicit name found without prior state is `Unowned`.
 */
import { createPhysicalName } from "alchemy/PhysicalName";
import { createInternalTags } from "alchemy/Tags";
import * as Effect from "effect/Effect";

const INTERNAL_PREFIX = "alchemy::";

/** Labels as Boat returns them. */
export type Labels = Readonly<Record<string, string | undefined>> | null | undefined;

/** The prefix Alchemy's ownership labels share. */
export const ALCHEMY_LABEL_PREFIX = "alchemy.";

/** `alchemy::stack` → `alchemy.stack`. */
export const toLabelKey = (key: string) =>
  key.startsWith(INTERNAL_PREFIX)
    ? `${ALCHEMY_LABEL_PREFIX}${key.slice(INTERNAL_PREFIX.length)}`
    : key;

/** This resource's ownership labels: `alchemy.stack`, `alchemy.stage`, `alchemy.id`. */
export const ownershipLabels = Effect.fn(function* (id: string) {
  const tags = yield* createInternalTags(id);
  return Object.fromEntries(
    Object.entries(tags).map(([key, value]) => [toLabelKey(key), value]),
  ) as Record<string, string>;
});

/** Whether labels carry this resource's ownership labels. */
export const hasOwnershipLabels = Effect.fn(function* (id: string, labels: Labels) {
  const expected = yield* ownershipLabels(id);
  return Object.entries(expected).every(([key, value]) => labels?.[key] === value);
});

/** Whether labels were set by any Alchemy stack or binding (for nuke). */
export const hasAnyAlchemyLabel = (labels: Labels) =>
  labels !== undefined && labels !== null && `${ALCHEMY_LABEL_PREFIX}stack` in labels;

/** Labels without Alchemy's own. */
export const userLabels = (labels: Labels): Record<string, string> =>
  Object.fromEntries(
    Object.entries(labels ?? {}).filter(
      (entry): entry is [string, string] =>
        entry[1] !== undefined && !entry[0].startsWith(ALCHEMY_LABEL_PREFIX),
    ),
  );

/** `key=value` filters for `listSandboxes`. */
export const labelFilter = (labels: Readonly<Record<string, string>>) =>
  Object.entries(labels).map(([key, value]) => `${key}=${value}`);

/**
 * A Boat name: the user's, or one generated from the stack, stage and
 * logical id. Lowercase letters, digits and dashes fit every Boat name rule
 * (snapshot names allow nothing else).
 */
export const boatName = (id: string, name: string | undefined, maxLength = 63) =>
  name !== undefined
    ? Effect.succeed(name)
    : createPhysicalName({ id, lowercase: true, maxLength, delimiter: "-" });

/**
 * Whether a name looks generated by `createPhysicalName` (lowercase, ending
 * in a base32 instance suffix). `list` reports only these, for nuke.
 */
export const isGeneratedName = (name: string | null | undefined): boolean =>
  typeof name === "string" && /^[a-z0-9][a-z0-9_-]*-[a-z2-7]{8,16}$/.test(name);
