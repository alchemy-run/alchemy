import * as DO from "@distilled.cloud/digitalocean";
import { isResolved } from "alchemy/Diff";
import { createPhysicalName } from "alchemy/PhysicalName";
import * as Provider from "alchemy/Provider";
import { Resource } from "alchemy/Resource";
import * as Effect from "effect/Effect";
import * as Option from "effect/Option";
import type * as Redacted from "effect/Redacted";
import { ignoreNotFound, noneIfNotFound } from "../internal/notFound.ts";
import { toRedactedOrUndefined } from "../internal/redacted.ts";
import type { Providers } from "../Providers.ts";
import { waitUntilOnline } from "./Cluster.ts";

export type UserProps = {
  /** The cluster the user belongs to. A change replaces the user. */
  clusterId: string;
  /**
   * User name. A change replaces the user.
   *
   * @default a generated physical name
   */
  name?: string;
  /**
   * MySQL only: the authentication plugin. A change replaces the user.
   *
   * @default "caching_sha2_password"
   */
  mysqlAuthPlugin?: "mysql_native_password" | "caching_sha2_password";
  /** PostgreSQL only: allow the user to start replication. Updates in place. */
  pgAllowReplication?: boolean;
  /** Create the user read-only (MySQL and PostgreSQL). A change replaces the user. */
  readonly?: boolean;
};

export type User = Resource<
  "DigitalOcean.Databases.User",
  UserProps,
  {
    /** The cluster the user belongs to. */
    clusterId: string;
    /** User name. */
    name: string;
    /** `normal`, or `primary` for the cluster's admin. */
    role: string | undefined;
    /** Password, generated by DigitalOcean. */
    password: Redacted.Redacted<string> | undefined;
  },
  never,
  Providers
>;

export type UserAttributes = User["Attributes"];

/**
 * A user in a Managed Database cluster, with a password DigitalOcean
 * generates. Pass `user.password` to a runtime as a secret.
 *
 * ### Creating a User
 * **Example:** An app user with its own password
 * ```typescript
 * const pg = yield* DigitalOcean.Databases.Cluster("db", {
 *   engine: "pg",
 *   size: "db-s-1vcpu-1gb",
 *   region: "nyc3",
 * });
 * const user = yield* DigitalOcean.Databases.User("app-user", { clusterId: pg.clusterId });
 * // Connect as user.name with user.password to pg.host:pg.port.
 * ```
 *
 * @see https://docs.digitalocean.com/reference/api/digitalocean/#operation/databases_add_user
 *
 * @resource
 * @product Managed Databases
 * @category Databases
 */
export const User = Resource<User>("DigitalOcean.Databases.User");

const physicalName = (id: string) =>
  createPhysicalName({ id, lowercase: true, maxLength: 63, delimiter: "_" });

const observe = (clusterId: string, name: string) =>
  noneIfNotFound(
    DO.getDatabaseUser({ database_cluster_uuid: clusterId, username: name }).pipe(
      Effect.map((r) => r.user),
    ),
  );

const toAttrs = (clusterId: string, user: DO.DatabaseUser): UserAttributes => ({
  clusterId,
  name: user.name,
  role: user.role,
  password: toRedactedOrUndefined(user.password),
});

export const UserProvider = () =>
  Provider.succeed(User, {
    stables: ["clusterId", "name"],
    read: Effect.fn(function* ({ id, olds, output }) {
      const name = output?.name ?? olds.name ?? (yield* physicalName(id));
      const clusterId = output?.clusterId ?? olds.clusterId;
      const observed = yield* observe(clusterId, name);
      return Option.getOrUndefined(Option.map(observed, (u) => toAttrs(clusterId, u)));
    }),
    diff: Effect.fn(function* ({ olds, news }) {
      if (!isResolved(news)) return undefined;
      if (
        news.clusterId !== olds.clusterId ||
        news.name !== olds.name ||
        news.mysqlAuthPlugin !== olds.mysqlAuthPlugin ||
        (news.readonly ?? false) !== (olds.readonly ?? false)
      ) {
        return { action: "replace" } as const;
      }
    }),
    reconcile: Effect.fn(function* ({ id, news, output }) {
      const name = output?.name ?? news.name ?? (yield* physicalName(id));
      const observed = yield* observe(news.clusterId, name);
      const user = yield* Option.match(observed, {
        onNone: () =>
          waitUntilOnline(news.clusterId).pipe(
            Effect.andThen(
              DO.addDatabaseUser({
                database_cluster_uuid: news.clusterId,
                name,
                readonly: news.readonly,
                mysql_settings:
                  news.mysqlAuthPlugin === undefined
                    ? undefined
                    : { auth_plugin: news.mysqlAuthPlugin },
              }),
            ),
            Effect.map((r) => r.user),
          ),
        onSome: Effect.succeed,
      });
      const allowReplication = news.pgAllowReplication;
      if (
        allowReplication !== undefined &&
        user.settings?.pg_allow_replication !== allowReplication
      ) {
        yield* DO.updateDatabaseUser({
          database_cluster_uuid: news.clusterId,
          username: name,
          settings: { pg_allow_replication: allowReplication },
        });
      }
      // GET returns the password too, so a resumed deploy keeps it.
      return toAttrs(news.clusterId, { ...user, password: user.password ?? output?.password });
    }),
    delete: Effect.fn(function* ({ output }) {
      yield* ignoreNotFound(
        DO.deleteDatabaseUser({ database_cluster_uuid: output.clusterId, username: output.name }),
      );
    }),
  });
