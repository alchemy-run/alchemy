/**
 * Shared Archil helpers: physical names, lookups by name, readiness waits.
 * Archil has no tags or labels, so ownership is the engine-generated
 * physical name (stack, stage, logical id and instance suffix).
 */
import * as archil from "@distilled.cloud/archil";
import { createPhysicalName } from "alchemy/PhysicalName";
import * as Data from "effect/Data";
import * as Duration from "effect/Duration";
import * as Effect from "effect/Effect";
import * as Option from "effect/Option";
import * as Schedule from "effect/Schedule";
import * as Stream from "effect/Stream";

/** Disk names: letters, digits, `-` and `_`, at most 100 characters. */
export const diskName = (id: string, name: string | undefined) =>
  name ? Effect.succeed(name) : createPhysicalName({ id, maxLength: 100, delimiter: "-" });

/** Lowercase letters, digits and single `-`, trimmed of leading/trailing `-`. */
export const toDnsLabel = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

/** Sandbox names: lowercase letters, digits and `-`, at most 63 characters. */
export const sandboxName = (id: string, name: string | undefined) =>
  name
    ? Effect.succeed(name)
    : createPhysicalName({ id, maxLength: 63, delimiter: "-", lowercase: true }).pipe(
        Effect.map(toDnsLabel),
      );

/** API token names. */
export const tokenName = (id: string, name: string | undefined) =>
  name ? Effect.succeed(name) : createPhysicalName({ id, maxLength: 64, delimiter: "-" });

/**
 * Whether a name was generated by Alchemy's physical-name scheme: it ends
 * with a delimiter and a base32 instance suffix.
 */
export const isAlchemyName = (name: string | undefined): boolean =>
  name !== undefined && /[-_][a-z2-7]{16}$/i.test(name);

/**
 * Whether a name carries a run-time client's owner prefix,
 * `alc-<id>-<hash of stack/stage/id>-` (see `runtimePrefix`). `list` (and so
 * `pnpm nuke`) finds disks and sandboxes created at run time by it.
 */
export const isRuntimeObjectName = (name: string | undefined): boolean =>
  name !== undefined && /^alc-[a-z0-9-]{1,14}-[0-9a-f]{8}-/.test(name);

/** A resource didn't reach a usable state within its time budget. */
export class ArchilNotReady extends Data.TaggedError("Archil.NotReady")<{
  readonly resource: string;
  readonly id: string;
  readonly status: string;
  readonly message: string;
}> {}

/** A resource reached a terminal failure state. */
export class ArchilFailed extends Data.TaggedError("Archil.Failed")<{
  readonly resource: string;
  readonly id: string;
  readonly status: string;
  readonly message: string;
}> {}

/**
 * Poll `observe` every 2 s (at most ~90 s) until `check` returns a value;
 * `check` returns `undefined` to keep waiting or fails on a terminal state.
 */
export const pollUntil = <A, B, E extends { readonly _tag: string }, R>(
  observe: Effect.Effect<A, E, R>,
  check: (value: A) => Effect.Effect<B | undefined, ArchilFailed>,
  pending: (value: A) => ArchilNotReady,
): Effect.Effect<B, E | ArchilFailed | ArchilNotReady, R> =>
  observe.pipe(
    Effect.flatMap((value) =>
      check(value).pipe(
        Effect.flatMap((done) =>
          done === undefined ? Effect.fail(pending(value)) : Effect.succeed(done),
        ),
      ),
    ),
    Effect.retry({
      while: (e) => e._tag === "Archil.NotReady",
      schedule: Schedule.spaced(Duration.seconds(2)),
      times: 45,
    }),
  );

/** Every disk (or every disk with this exact name), following `nextCursor`. */
export const listAllDisks = (name?: string) =>
  Stream.paginate(undefined as string | undefined, (cursor) =>
    archil
      .listDisks({ name, cursor, limit: 1000 })
      .pipe(
        Effect.map(({ data, nextCursor }) => [data, Option.fromNullishOr(nextCursor)] as const),
      ),
  );

/**
 * Find a live disk by exact name. Archil keeps listing a deleted disk under
 * its name for a while, so those are skipped.
 */
export const findDiskByName = Effect.fn(function* (name: string) {
  return Option.getOrUndefined(
    yield* listAllDisks(name).pipe(
      Stream.filter((disk) => disk.name === name && disk.status !== "deleted"),
      Stream.runHead,
    ),
  );
});

/** Get a disk by id; `undefined` when it doesn't exist. */
export const getDisk = (id: string) =>
  archil.getDisk({ id }).pipe(
    Effect.map(({ data }) => (data.status === "deleted" ? undefined : data)),
    Effect.catchTag("NotFound", () => Effect.undefined),
  );

/** Wait until a disk is `available`. */
export const waitForDisk = (id: string) =>
  pollUntil(
    archil.getDisk({ id }).pipe(Effect.map(({ data }) => data)),
    (disk) =>
      disk.status === "available"
        ? Effect.succeed(disk)
        : disk.status === "failed"
          ? Effect.fail(
              new ArchilFailed({
                resource: "Disk",
                id,
                status: disk.status,
                message: `Disk ${disk.name} failed to provision`,
              }),
            )
          : Effect.undefined,
    (disk) =>
      new ArchilNotReady({
        resource: "Disk",
        id,
        status: disk.status,
        message: `Disk ${disk.name} is ${disk.status}`,
      }),
  );

/** Wait until a disk is gone after a delete. */
export const waitForDiskGone = (id: string) =>
  pollUntil(
    getDisk(id),
    (disk) => (disk === undefined ? Effect.succeed(true as const) : Effect.undefined),
    (disk) =>
      new ArchilNotReady({
        resource: "Disk",
        id,
        status: disk?.status ?? "deleted",
        message: `Disk ${disk?.name ?? id} is still ${disk?.status}`,
      }),
  ).pipe(Effect.asVoid);

/** Every sandbox in the account (optionally only those mounting a disk). */
export const listSandboxes = Effect.fn(function* (filesystem?: string) {
  const { data } = yield* archil.listSandboxes({ filesystem });
  return data.sandboxes ?? [];
});

/** Find a sandbox by exact name. */
export const findSandboxByName = Effect.fn(function* (name: string) {
  return (yield* listSandboxes()).find(
    (sandbox) => sandbox.name === name && sandbox.status !== "deleted",
  );
});

/** Get a sandbox by id; `undefined` when it doesn't exist. */
export const getSandbox = (sid: string) =>
  archil.getSandbox({ sid }).pipe(
    Effect.map(({ data }) => (data.status === "deleted" ? undefined : data)),
    Effect.catchTag("NotFound", () => Effect.undefined),
  );

const settledSandboxStates = new Set(["running", "paused", "stopped", "exited"]);

/** Wait until a sandbox leaves its transitional states. */
export const waitForSandbox = (sid: string) =>
  pollUntil(
    archil.getSandbox({ sid }).pipe(Effect.map(({ data }) => data)),
    (sandbox) =>
      settledSandboxStates.has(sandbox.status)
        ? Effect.succeed(sandbox)
        : sandbox.status === "failed"
          ? Effect.fail(
              new ArchilFailed({
                resource: "Sandbox",
                id: sid,
                status: sandbox.status,
                message: `Sandbox ${sandbox.name} failed${sandbox.exit_reason ? `: ${sandbox.exit_reason}` : ""}`,
              }),
            )
          : Effect.undefined,
    (sandbox) =>
      new ArchilNotReady({
        resource: "Sandbox",
        id: sid,
        status: sandbox.status,
        message: `Sandbox ${sandbox.name} is ${sandbox.status}`,
      }),
  );

/** States a sandbox can be deleted from. */
export const deletableSandboxStates = new Set(["stopped", "exited", "failed"]);

/** Wait until a stopping sandbox is stopped (or exited, or failed). */
export const waitForSandboxStopped = (sid: string) =>
  pollUntil(
    getSandbox(sid),
    (sandbox) =>
      sandbox === undefined || deletableSandboxStates.has(sandbox.status)
        ? Effect.succeed(true as const)
        : Effect.undefined,
    (sandbox) =>
      new ArchilNotReady({
        resource: "Sandbox",
        id: sid,
        status: sandbox?.status ?? "deleted",
        message: `Sandbox ${sandbox?.name ?? sid} is still ${sandbox?.status}`,
      }),
  ).pipe(Effect.asVoid);

/** Wait until a sandbox is gone after a delete. */
export const waitForSandboxGone = (sid: string) =>
  pollUntil(
    getSandbox(sid),
    (sandbox) =>
      sandbox === undefined || sandbox.status === "deleting"
        ? Effect.succeed(true as const)
        : Effect.undefined,
    (sandbox) =>
      new ArchilNotReady({
        resource: "Sandbox",
        id: sid,
        status: sandbox?.status ?? "deleted",
        message: `Sandbox ${sandbox?.name ?? sid} is still ${sandbox?.status}`,
      }),
  ).pipe(Effect.asVoid);

/** Wait until an image build finishes. */
export const waitForImage = (imageId: string) =>
  pollUntil(
    archil.getImage({ image_id: imageId }).pipe(Effect.map(({ data }) => data)),
    (image) =>
      image.status === "ready"
        ? Effect.succeed(image)
        : image.status === "failed"
          ? Effect.fail(
              new ArchilFailed({
                resource: "Image",
                id: imageId,
                status: `failed${image.failure_reason ? ` (${image.failure_reason})` : ""}`,
                message: `Image ${image.source} failed to build${image.failure_reason ? `: ${image.failure_reason}` : ""}`,
              }),
            )
          : Effect.undefined,
    (image) =>
      new ArchilNotReady({
        resource: "Image",
        id: imageId,
        status: image.status,
        message: `Image ${image.source} is ${image.status}`,
      }),
  );
